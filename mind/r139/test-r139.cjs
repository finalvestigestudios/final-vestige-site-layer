'use strict';
/* Native run: node mind/r139/test-r139.cjs. External tooling is not needed.
 * The same test entry can be executed with a V8/CommonJS shim that maps fs.readFileSync
 * to exact GitHub-committed file contents; that is NOT a native Node/browser run. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const dir = __dirname;
const read = name => fs.readFileSync(path.join(dir, name), 'utf8');
const A = read('zen12-variant-a.html'), B=read('zen12-variant-b.html');
const H=read('mind-hub-wp-draft.html'), G=read('total-focus-independent-buyer-guide.md');
const C=read('conversion-acceptance.md'), M=JSON.parse(read('claim-register.json'));
let passed=0;
const check=(name,fn)=>{fn();passed++;};
const contains=(s,x)=>assert.ok(s.includes(x),'missing: '+x);
const buyer = s=>s.match(/<section id="buyer-information"[\s\S]*?<\/section>/)?.[0];
const offer = s=>s.match(/<section class="offer"[\s\S]*?<\/section>/)?.[0];
const safe = s => !/<script\b|<form\b|<iframe\b|<video\b|\bautoplay\b|href=["'][^"']*(?:affiliates\.inspire3|[?&](?:ref|aff|affiliate|tid|subid)=)/i.test(s);
const disclosure=s=>{const o=offer(s);return !!o&&o.includes('If you purchase through an approved link here in the future, Final Vestige may earn a commission')&&o.includes('disabled aria-disabled="true"')&&o.indexOf('class="disclose"')<o.indexOf('<button');};
const net=(sessions,settled,refunds,fees,costs)=>{
 if([sessions,settled,refunds,fees,costs].some(x=>!Number.isFinite(x))||sessions<=0||[refunds,fees,costs].some(x=>x<0))return null;
 return 1000*(settled-refunds-fees-costs)/sessions;
};
check('buyer copy parity A B',()=>assert.equal(buyer(A),buyer(B)));
check('merchant CTA parity A B',()=>assert.equal(offer(A),offer(B)));
check('disabled CTA with adjacent understandable disclosure A',()=>assert.ok(disclosure(A)));
check('disabled CTA with adjacent understandable disclosure B',()=>assert.ok(disclosure(B)));
check('text-only A has no film content',()=>assert.ok(!A.includes('<aside class="film"')));
check('B film clearly hypothetical',()=>{contains(B,'film, not recorded');contains(B,'00:33–00:40');contains(B,'<details>');});
check('B original accessible poster label',()=>contains(B,'role="img" aria-label='));
check('all markup has static no-remote-script/no-form controls',()=>[A,B,H].forEach(x=>assert.ok(safe(x))));
check('no duplicate email capture',()=>[A,B,H].forEach(x=>assert.ok(!/<form\b/i.test(x))));
check('both variants link existing Focus',()=>[A,B].forEach(x=>contains(x,'https://finalvestige.com/focus/')));
check('A B have responsive viewport',()=>[A,B].forEach(x=>contains(x,'name="viewport"')));
check('A B reduced motion',()=>[A,B].forEach(x=>contains(x,'prefers-reduced-motion:reduce')));
check('A B local noindex',()=>[A,B].forEach(x=>contains(x,'noindex,nofollow')));
check('no unapproved merchant earning href',()=>[A,B,H].forEach(x=>assert.ok(!/href=["'][^"']*(?:affiliates\.inspire3|[?&](?:aff|subid|affiliate)=)/i.test(x))));
check('hub existing live destinations only',()=>['https://finalvestige.com/focus/','https://finalvestige.com/2026/11/02/change-blindness/','https://finalvestige.com/free-resources/puysegurs-animal-magnetism-files/'].forEach(x=>contains(H,x)));
check('guide substantial and source-rich',()=>{assert.ok(G.split(/\s+/).length>=1500);['https://doi.org/10.1016/j.concog.2024.103730','https://hypnosislive.com/faq','https://www.ftc.gov/'].forEach(x=>contains(G,x));});
check('explicit distinct Total Focus vs Hypnotize Yourself',()=>['Total Focus','Hypnotize Yourself','not the same SKU'].forEach(x=>contains(G,x)));
check('pricing inconsistency and refund caveat',()=>['$24.44','$17.95','five sessions per year'].forEach(x=>contains(G,x)));
check('matrix sources complete',()=>M.claims.forEach(c=>c.source_ids.forEach(k=>assert.ok(M.sources[k],'missing '+k))));
check('claims and closed gates nonempty',()=>{assert.ok(M.claims.length>=18);assert.ok(Object.values(M.release_gates).length>=15);assert.ok(Object.values(M.release_gates).every(v=>v===false));});
check('monetization UNKNOWN not 0',()=>['qualified_human_sessions','verified_paid_orders','realized_net_revenue','net_revenue_per_1000_qualified_sessions'].forEach(k=>assert.equal(M.traffic_and_conversion[k],null)));
check('fallback Payhip SKU not invented',()=>assert.equal(M.owned_product_fallback.mind_paid_sku,null));
check('Grok three pathways and no invented ID',()=>{contains(C,'Change Blindness');contains(C,'Puységur');contains(C,'Attentional Blink');contains(C,'UNKNOWN / UNKNOWN');});
check('7/30-day net revenue contract',()=>{contains(C,'7/30-day cohorts');contains(C,'merchant_confirmed_paid_order');contains(C,'affiliate_outbound');});
check('commission and click semantics',()=>{contains(C,'affiliate_outbound');contains(C,'net_per_1000');contains(C,'NOT COMPUTABLE');});
check('net arithmetic nominal case',()=>assert.equal(net(200,200,10,20,10),800));
check('net rejects missing & zero denominator',()=>{assert.equal(net(null,100,0,0,0),null);assert.equal(net(0,100,0,0,0),null);});
check('net rejects impossible negative fee',()=>assert.equal(net(300,100,0,-1,0),null));
check('mutation: deleting disclosure fails',()=>assert.ok(!disclosure(A.replace(/<p class="disclose">[\s\S]*?<\/p>/,''))));
check('mutation: enabling merchant button fails',()=>assert.ok(!disclosure(A.replace('disabled aria-disabled="true"',''))));
check('mutation: script injection fails',()=>assert.ok(!safe(B+'<script>alert(1)</script>')));
check('mutation: new capture form fails',()=>assert.ok(!safe(H+'<form></form>')));
check('mutation: affiliate parameter fails',()=>assert.ok(!safe(B+'<a href="https://sample.example/?affiliate=test">x</a>')));
check('mutation: broken buyer source parity fails',()=>assert.notEqual(buyer(A.replace('Twelve levels','Eleven levels')),buyer(B)));
check('mutation: source gap fails',()=>assert.ok(!M.sources.NEVER_DECLARED));
process.stdout.write('Mind R139 source controls: '+passed+'/'+passed+' assertions PASS\n');
module.exports={passed};
