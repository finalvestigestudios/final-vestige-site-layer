/* Mind R147 regression test. Run node mind/r147/test-r147.cjs from checkout of R147 branch. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const dir=__dirname;
const h=fs.readFileSync(path.join(dir,'zen12-premium-buyer-bridge-review-only.html'),'utf8');
const a=fs.readFileSync(path.join(dir,'attentional-blink-and-meditation-investigation.md'),'utf8');
const g=fs.readFileSync(path.join(dir,'zen12-premium-independent-buyer-guide.md'),'utf8');
const m=JSON.parse(fs.readFileSync(path.join(dir,'claim-source-offer-verification.json'),'utf8'));
let count=0;
function check(name,test){assert.ok(test,name);count++}
check('release gated',h.includes('data-release="HARD_HOLD"'));
check('exact Premium offer',h.includes('data-offer="zen12-premium"')&&g.includes('Zen12 Premium'));
const buttons=[...h.matchAll(/<button\b[^>]*>/g)].map(x=>x[0]);
check('inert paid button',buttons.some(b=>/\sdisabled(?:\s|=|>)/.test(b)));
check('exactly one button and truly disabled',buttons.length===1 && /\sdisabled(?:\s|=|>)/.test(buttons[0]));
check('clear near-link commission disclosure',/Prospective affiliate disclosure:[\s\S]{0,400}may earn a commission[\s\S]{0,500}<button/.test(h));
check('free Focus only enabled CTA',h.includes('href="https://finalvestige.com/focus/"')&&h.includes('Explore the free'));
check('no active affiliate URL',!(/utm_affiliate|[?&](?:ref|aff_id|hop)=|clickbank|affiliate_click_redirect/.test(h)));
check('no scripts or external media',!(/<script\b|<iframe\b|<video\b|<form\b/i.test(h)));
check('no hidden tracking pixels',!(/<img\b|dataLayer|gtag\(/i.test(h)));
check('no fabricated price checkout',h.includes('not a verified final checkout price'));
check('no video claim',h.includes('There is no playable media'));
check('no JS and semantic article',h.includes('<article')&&h.includes('aria-labelledby'));
check('reduced motion provision',h.includes('prefers-reduced-motion'));
check('responsive grid',h.includes('@media(min-width:760px)'));
check('legitimate seller source',h.includes('https://zen12.com/hnp'));
check('scholarly links',a.includes('pubmed.ncbi.nlm.nih.gov/1500880')&&a.includes('10.1371/journal.pbio.0050138'));
check('does not claim product study',a.includes('did not test Zen12')&&g.includes('not after using Zen12 Premium'));
check('no unqualified meditation hour efficacy',a.includes('not established')&&g.includes('None of these studies validates'));
check('original article length >= 1400',a.trim().split(/\s+/).length>=1400);
check('guide length >= 700',g.trim().split(/\s+/).length>=700);
check('claim register adequate',m.claims.length>=18&&m.evidence.length>=10);
check('all commerce gates closed',Object.values(m.release_gates).every(v=>v===false));
check('media IDs unverified',m.creator_fit.every(v=>v.source_asset_id===null));
check('published vs draft correctly split',m.creator_fit[2].article===null);
check('revenue not computable',m.measurement.report==='NOT_COMPUTABLE');
check('all source IDs valid',m.claims.every(c=>m.evidence.some(s=>s.id===c.source)));
check('no sale invented',m.claims.find(c=>c.id==='C20').decision==='UNKNOWN_NOT_COMPUTABLE');
check('comparison transparency',h.includes('Text-only guide A')&&h.includes('forty-second')===false);
check('prospective disclosure not endorsed product',g.includes('No product endorsement'));
check('no 2nd subscription form',!(/<form\b/.test(h)));
console.log('R147 native Node structural checks PASS '+count+'/'+count);
