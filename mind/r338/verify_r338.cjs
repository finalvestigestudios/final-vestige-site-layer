#!/usr/bin/env node
/* R338 source-only regression validator. Run from repo root: node mind/r338/verify_r338.cjs.
   Does not perform browser, merchant, WordPress, media-playback or network tests. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const dir = __dirname;
const read = name => fs.readFileSync(path.join(dir,name),'utf8');
const a=read('zen12-a-text.html'),b=read('zen12-b-optional-film.html');
const hub=read('MIND_HUB_WP_REVIEW_ONLY.html');
const paper=read('THE_GORILLA_WAS_SLOW.md');
const poster=read('zen12-42s-poster.svg');
const vtt=read('zen12-42s-captions.vtt');
const matrix=JSON.parse(read('SOURCE_CLAIM_COMMERCE_MATRIX.json'));
const plan=read('CONVERSION_ATTRIBUTION_RELEASE.md');
const stripFilm=h=>h.replace(/<section class="panel film"[\s\S]*?<\/section>/,'').replaceAll('B: optional original film storyboard','A: text-only');
let checks=0;
function must(condition,message){assert.ok(condition,message);checks++}
function gateHtml(h,tag){
  must(h.startsWith('<!doctype html>'),tag+' document');
  must(h.includes('<html lang="en">'),tag+' language');
  must(h.includes('name="viewport"'),tag+' viewport');
  must(h.includes('noindex,nofollow'),tag+' noindex');
  must(h.includes('https://finalvestige.com/focus/'),tag+' existing Focus');
  must(h.includes('disclosure"><strong>Prospective earning disclosure:'),tag+' near CTA disclosure');
  must(h.includes('may earn a commission at no additional cost to you'),tag+' plain earnings');
  must(h.includes('disabled aria-disabled="true"'),tag+' purchase disabled');
  must(h.includes('First six levels, 24 MP3s'),tag+' beginner tier');
  must(h.includes('All twelve levels, 48 MP3s'),tag+' premium tier');
  must(h.includes('Final six levels, 24 MP3s'),tag+' advanced tier');
  must(h.includes('not a confirmed current checkout total'),tag+' no evergreen price');
  must(!/<script\b|<iframe\b|<form\b|<input\b/i.test(h),tag+' no script/frame/form/input');
  must(!/<a\b[^>]*href=["']https?:\/\/(?:www\.)?(?:zen12\.com|inspire3\.com|affiliates\.inspire3\.com|hypnosislive\.com|brainwaveshots\.com)/i.test(h),tag+' no merchant link');
  must(!/\b(?:autoplay|onclick|onerror)\s*=/i.test(h),tag+' no autoplay/inline handler');
  must(!/<button(?![^>]*disabled)[^>]*>[^<]*(?:review merchant|buy|checkout)/i.test(h),tag+' no active paid button');
  must(h.includes('prefers-reduced-motion'),tag+' reduced motion');
  must(h.includes(':focus-visible'),tag+' focus visible');
}
gateHtml(a,'A');gateHtml(b,'B');
must(stripFilm(b)===a,'Core copy must be identical between A and B after optional film removed');
must(b.includes('zen12-42s-poster.svg'),'B references original poster');
must(b.includes('zen12-42s-captions.vtt'),'B mentions VTT');
must(b.includes('<details><summary>'),'B transcript accessible with no JS');
must(!b.includes('<video'),'Storyboard not falsely presented as playable film');
must(poster.startsWith('<svg ')&&poster.includes('<title ')&&poster.includes('<desc '),'original SVG accessibility');
must(vtt.startsWith('WEBVTT'),'VTT header');
must((vtt.match(/-->/g)||[]).length===6,'six timed caption cues');
must(vtt.includes('00:00:42.000'),'42-second storyboard duration');
must(hub.includes('noindex,nofollow'),'hub is unpublished');
must(hub.includes('four-stream')===false || hub.includes('Perception'),'hub content exists');
must(hub.includes('Perception &amp; Attention')&&hub.includes('History of Suggestion')&&hub.includes('Practice &amp; Reflection')&&hub.includes('Tools Under Review'),'four streams complete');
must(!/<script\b|<form\b|<iframe\b/i.test(hub),'hub has no injected UI');
must(paper.split(/\s+/).length>=1400,'substantive original study');
must(paper.includes('https://doi.org/10.1073/pnas.2214930120'),'new study primary citation');
must(paper.includes('https://doi.org/10.1068/p281059'),'classic primary citation');
must(paper.includes('https://finalvestige.com/free-resources/puysegurs-animal-magnetism-files/'),'archive source');
must(matrix.source_records.length>=15,'source count');
must(matrix.claims.length>=20,'claim status matrix');
must(matrix.release_gates.length>=15,'release gates');
must(matrix.release_gates.every(g=>g.passed===false),'all commerce gates held');
must(matrix.affiliate_partner_eligibility==='NOT VERIFIED','no invented acceptance');
must(matrix.issued_affiliate_url==='WITHHELD','no invented earning URL');
must(matrix.payhip_paid_mind_sku==='NOT VERIFIED','no invented owned SKU');
const ids=new Set(matrix.source_records.map(s=>s.id));
must(matrix.claims.every(c=>c.source_ids.every(id=>ids.has(id))),'all source ids resolve');
must(plan.includes('net_revenue_per_1000_human_sessions'),'main commercial KPI');
must(plan.includes('merchant_confirmed_affiliate_order'),'affiliate purchase distinct');
must(plan.includes('confirmed_signup'),'opt-in not a click');
must(plan.includes('no new scripts') || plan.includes('no new scripts/SaaS'),'privacy protections');
let negative=0;
const rejects=(unsafe,test)=>{must(!test(unsafe),'unsafe mutation unexpectedly passed');negative++};
rejects(a.replace('disabled aria-disabled="true"',''),h=>h.includes('disabled aria-disabled="true"'));
rejects(a.replace('Prospective earning disclosure:','MISSING'),h=>h.includes('Prospective earning disclosure:'));
rejects(a+'<script src="https://example.invalid/track.js"></script>',h=>!/<script\b/.test(h));
rejects(a.replace('All twelve levels, 48 MP3s','All twelve levels, 24 MP3s'),h=>h.includes('All twelve levels, 48 MP3s'));
rejects(a.replace('noindex,nofollow','index,follow'),h=>h.includes('noindex,nofollow'));
rejects(b.replace('zen12-42s-captions.vtt','missing-captions.vtt'),h=>h.includes('zen12-42s-captions.vtt'));
rejects(b.replace('may earn a commission at no additional cost to you','may earn something'),h=>h.includes('may earn a commission at no additional cost to you'));
rejects(a+'<a href="https://zen12.com/buy-now">hidden offer</a>',h=>!/<a\b[^>]+href="https:\/\/zen12\.com/.test(h));
rejects(a.replace('First six levels, 24 MP3s','First six levels, 48 MP3s'),h=>h.includes('First six levels, 24 MP3s'));
rejects(a.replace('https://finalvestige.com/focus/','#'),h=>h.includes('https://finalvestige.com/focus/'));
console.log('R338 PASS:',checks,'source assertions;',negative,'adversarial mutations detected. Static source only: browser / media / merchant UNTESTED.');
