"use strict";
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.resolve(__dirname,".."),get=p=>fs.readFileSync(path.join(root,p),"utf8");
const A=get("ARTICLE.md"),H=get("article-wordpress-draft.html"),G=get("GUIDE.md"),P=get("get-super-organized-wordpress-draft.html"),M=JSON.parse(get("claims.json")),N=JSON.parse(get("navigation.json")),C=get("conversion-playbook.md"),V=get("video-script.md");
const rows=[];
function ck(name,predicate){try{assert.ok(predicate(),name);rows.push(name);}catch(e){process.stderr.write("FAIL "+name+"\n"+String(e)+"\n");process.exitCode=1;}}
ck("long evidence investigation",()=>A.trim().split(/\s+/).length>=2400);
ck("complete product guide",()=>G.trim().split(/\s+/).length>=1100);
ck("1991 and 1994 study samples",()=>A.includes("237 participants")&&A.includes("78 participants")&&G.includes("237 participants"));
ck("positive laboratory counterevidence",()=>A.includes("Farooqui")&&A.includes("Bustin"));
ck("free Focus in both pages",()=>H.includes("https://finalvestige.com/focus/")&&P.includes("https://finalvestige.com/focus/"));
ck("Puysegur historic source",()=>H.includes("puysegurs-animal-magnetism-files"));
ck("no script/iframe forms",()=>![H,P].some(x=>/<(?:script|iframe|form)\b/i.test(x)));
ck("exactly one article H1",()=> (H.match(/<h1\b/g)||[]).length===1);
ck("exactly one guide H1",()=> (P.match(/<h1\b/g)||[]).length===1);
ck("no nested main landmarks",()=>!/<main\b/.test(P));
ck("disabled merchant CTA",()=>/<button[^>]*disabled[^>]*>/.test(P));
ck("affiliate disclosure before CTA",()=>P.indexOf('id="fvsg-disclosure"')>=0&&P.indexOf('id="fvsg-disclosure"')<P.indexOf('<button type="button" class="fvsg-no-offer"'));
ck("merchant links not active in guide or investigation",()=>![H,P].some(x=>/<a[^>]*href="https:\/\/(?:www\.)?(?:subliminalguru|inspire3)\.com/i.test(x)));
ck("no tracking code",()=>!/[<]script|googletagmanager|facebook\.net|dataLayer\.push/i.test(P));
ck("responsive for phones",()=>H.includes("@media(max-width:640px)")&&P.includes("@media(max-width:520px)"));
ck("reduced motion respected",()=>H.includes("prefers-reduced-motion:reduce")&&P.includes("prefers-reduced-motion:reduce"));
ck("40+ claim rows",()=>M.claims.length>=40);
ck("every row independently sourced",()=>M.claims.every(x=>x.id&&x.claim&&x.limit&&x.decision&&x.sources?.length&&x.sources.every(s=>M.sources[s])));
ck("IDs unique",()=>new Set(M.claims.map(x=>x.id)).size===M.claims.length);
ck("unverified seller efficacy never adopted",()=>M.claims.filter(x=>x.kind==="seller-efficacy").every(x=>x.decision==="do-not-adopt"));
ck("no unverified affiliate activation",()=>M.affiliate_approved===false&&M.affiliate_url===null&&N.no_active_commercial_links);
ck("draft URLs marked unpublished",()=>N.article.status==="draft"&&N.offer_guide.status==="draft");
ck("no new signup",()=>N.no_new_signup===true&&!/<form\b/.test(P));
ck("source scope current",()=>M.as_of==="2026-10-30"&&M.sources.APS91.url.startsWith("https://"));
ck("privacy no PII",()=>C.includes("Do **not** collect email, device fingerprint"));
ck("film not falsely produced",()=>V.includes("NOT an actual video file"));
ck("canonical merchant page source",()=>M.sources.OFFER.url.endsWith("/get-super-organized"));
process.stdout.write(rows.length+" passed / "+(rows.length+(process.exitCode?1:0))+" checked\n");
