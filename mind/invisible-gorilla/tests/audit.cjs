function audit(i) {
const checks=[];const check=(label,fn)=>{try{if(!fn())throw Error("false");checks.push({label,pass:true});}catch(e){checks.push({label,pass:false,error:String(e.message)})}};
const a=i.article,h=i.html,c=i.ledger,n=i.nav,p=i.playbook,f=i.film;
check("2511 word source article",()=>a.trim().split(/\s+/).length>=2300);
check("1999 primary study",()=>a.includes("https://doi.org/10.1068/p281059"));
check("2005 primary study",()=>a.includes("https://doi.org/10.1037/0033-295X.112.1.217"));
check("2010 primary study",()=>a.includes("https://doi.org/10.1068/i0386"));
check("2013 primary study",()=>a.includes("https://doi.org/10.1177/0956797613479386"));
check("small medical cohort caveat",()=>/small.*(attention|experiment)/i.test(a));
check("misleading cancer miss rate rejected",()=>a.includes("not a study of routine medical errors"));
check("misleading fake test rejected",()=>a.includes("psychological assessment"));
check("seller product not scientifically proven",()=>a.includes("none of the primary studies")||a.includes("None of the primary studies"));
check("free resource linked",()=>a.includes("https://finalvestige.com/focus/"));
check("archival first-party research linked",()=>a.includes("https://finalvestige.com/free-resources/puysegurs-animal-magnetism-files/"));
check("one h1",()=>((h.match(/<h1\b/g)||[]).length===1));
check("semantic article no nested main",()=>h.includes('<article class="fv-ib"')&&!/<main\b/i.test(h));
check("article labeled heading",()=>h.includes('aria-labelledby="fv-ib-title"'));
check("native details and summary",()=>h.includes("<details><summary>"));
check("independent illustration non-diagnostic",()=>h.includes("not a psychological test"));
check("original ledger count shown",()=>h.includes("eight SOURCE cards"));
check("native illustration static all cards",()=>((h.match(/<span>/g)||[]).length>=20));
check("no JavaScript",()=>!/<script\b|onclick=|onload=/i.test(h));
check("no signup form",()=>!/<form\b|<input\b/i.test(h));
check("no merchant anchors",()=>!/href="https:\/\/(zen12|inspire3|hypnosislive|brainwaveshots)\.com/i.test(h));
check("no staged dead buyer guide link",()=>!h.includes('href="/mind/zen12-guide/"'));
check("no telemetry",()=>!/gtag\(|fbq\(|sendBeacon|fetch\(|localStorage|document\.cookie|googletagmanager/i.test(h));
check("CSS selector scoped",()=>h.includes(".fv-ib{--bg:"));
check("touch/mobile 800",()=>h.includes("@media(max-width:800px)"));
check("touch/mobile 420",()=>h.includes("@media(max-width:420px)"));
check("prefers reduced motion",()=>h.includes("prefers-reduced-motion:reduce"));
check("visible keyboard focus",()=>h.includes(":focus-visible"));
check("no copied images or embedded media",()=>!/<img\b|<iframe\b|<video\b/i.test(h));
check("forty distinct claims",()=>c.claims.length===40&&new Set(c.claims.map(x=>x.id)).size===40);
check("twelve sources",()=>c.sources.length===12);
check("all claims map real sources",()=>c.claims.every(x=>c.sources.some(y=>y.id===x.source)));
check("decision enum",()=>c.claims.every(x=>["supported","seller-only","qualified","exclude"].includes(x.decision)));
check("study vs vendor classification",()=>c.sources.some(x=>x.id==="zen"&&x.category==="vendor"));
check("claim rejects radiology overreach",()=>c.claims.some(x=>x.claim.includes("83% real")&&x.decision==="exclude"));
check("claim rejects false Zen12 effect",()=>c.claims.some(x=>x.claim.includes("one hour equivalent")&&x.decision==="exclude"));
check("no affiliate approved",()=>c.affiliate.approved===false);
check("no affiliate link",()=>c.affiliate.tracking_link===null);
check("no invented price/payout",()=>c.affiliate.price===null&&c.affiliate.payout===null);
check("no product personal test",()=>c.affiliate.product_tested===false);
check("route not live",()=>n.article_live===false&&n.hub_live===false&&n.guide_live===false);
check("no earners in nav",()=>n.active_affiliate_links.length===0);
check("no trackers",()=>n.tracking_installed===false);
check("free-first copy",()=>p.includes("Focus Fieldbook")&&p.includes("No email gate"));
check("exact seller About consulted",()=>p.includes("https://zen12.com/about"));
check("merchant freebie newsletter disclosed",()=>p.includes("https://zen12.com/welcome")&&p.includes("newsletter"));
check("near earning link disclosure templated",()=>p.includes("may earn a commission at no additional cost"));
check("no purchase inferred from click",()=>p.includes("Click ≠ sale"));
check("consumer privacy limits",()=>p.includes("raw referrer URLs")&&p.includes("fingerprinting"));
check("film specifically script not finished video",()=>f.includes("Not a produced MP4"));
check("film rejects medical distortion",()=>f.includes("NOT A CANCER MISS RATE"));
check("film sound caption and no autoplay",()=>f.includes("Caption all narration")&&f.includes("No autoplay sound"));
check("film copyright safeguard",()=>f.includes("No copyrighted 1999 gorilla footage"));
check("film disclosure media fallback",()=>f.includes("visibly AND audibly"));
check("commercial independence",()=>p.includes("Each stage must justify itself"));
return {passed:checks.filter(x=>x.pass).length,failed:checks.filter(x=>!x.pass).length,checks};
}
if(typeof module!=="undefined")module.exports={audit};