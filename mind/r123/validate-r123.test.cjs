// Node >= 18: node --test mind/r123/validate-r123.test.cjs
// Source-only gates, NOT substitutes for real browser, native CI or merchant proof.
'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const at=n=>fs.readFileSync(path.join(__dirname,n),'utf8');
const article=at('attentional-blink-investigation.md');
const a=at('zen12-guide-A-text.html');
const b=at('zen12-guide-B-storyboard.html');
const hub=at('mind-hub-wordpress-custom-html-draft.html');
const ledger=JSON.parse(at('claim-proof-and-eligibility.json'));
const plan=at('conversion-release-and-creator-handoff.md');
const noSellerAnchor=/\<a\s[^>]*href\s*=\s*["']https?:\/\/(?:www\.)?(?:zen12\.com|inspire3\.com|hypnosislive\.com|brainwaveshots\.com|affiliates\.inspire3\.com)\/[^"']*["']/i;
const merchantButton=/<button\s[^>]*disabled\b[^>]*>Zen12 purchasing link unavailable<\/button>/i;
const stripFilm = s=>s.replace(/<section class="storyboard"[\s\S]*?<\/section>/,'');
function checks(){
const results=[];
function check(label, condition){results.push({label,pass:!!condition});}
check('original article > 1400 words',article.trim().split(/\s+/).length>1400);
check('research 1992',article.includes('1992')&&article.includes('Raymond'));
check('research 2007',article.includes('Slagter')&&article.includes('three months'));
check('no research product review',article.includes('No commercial')||article.includes('no sponsored product'));
check('research source URLs >=5',(article.match(/https:\/\//g)||[]).length>=5);
check('free existing Fieldbook',article.includes('https://finalvestige.com/focus/'));
check('historical link',article.includes('puysegurs-animal-magnetism-files/'));
check('no commerce source in article',!noSellerAnchor.test(article));
check('ledger sources >=15',ledger.sources.length>=15);
check('ledger claims >=15',ledger.claims.length>=15);
check('ledger gates >=15',ledger.commercial_release_gates.length>=15);
check('all commercial gates closed',ledger.commercial_release_gates.every(g=>g.status==='CLOSED'));
check('all ledger sources have urls',ledger.sources.every(s=>/^https:\/\//.test(s.url)));
check('all claim source references valid',ledger.claims.every(c=>ledger.sources.some(s=>s.id===c.source_id)));
check('rejection of hour-equivalence',ledger.claims.some(c=>c.id==='zen12_one_hour_equivalence'&&c.status==='REJECT_UNSUBSTANTIATED'));
check('research review not overclaimed',ledger.claims.some(c=>c.id==='binaural_entrainment'&&c.status==='NOT_ESTABLISHED'));
check('buyer privacy gate closed',ledger.commercial_release_gates.some(g=>g.id==='aggregate_only_affiliate_reporting'&&g.status==='CLOSED'));
check('merchant offer acceptance closed',ledger.commercial_release_gates.some(g=>g.id==='named_partner_acceptance'&&g.status==='CLOSED'));
check('both variants same content except film',stripFilm(b)===a);
check('B contains unique film section',b.includes('data-experiment="video"')&&!a.includes('data-experiment="video"'));
check('A no autoplay',!/<video[^>]*\bautoplay\b/i.test(a));
check('B no autoplay',!/<video[^>]*\bautoplay\b/i.test(b));
check('A no merchant anchor',!noSellerAnchor.test(a));
check('B no merchant anchor',!noSellerAnchor.test(b));
check('A purchase button native disabled',merchantButton.test(a));
check('B purchase button native disabled',merchantButton.test(b));
check('A disclosure adjacent to CTA',a.indexOf('class="disclosure"')<a.indexOf('Zen12 purchasing link unavailable')&&a.indexOf('Zen12 purchasing link unavailable')-a.indexOf('class="disclosure"')<700);
check('B disclosure adjacent to CTA',b.indexOf('class="disclosure"')<b.indexOf('Zen12 purchasing link unavailable')&&b.indexOf('Zen12 purchasing link unavailable')-b.indexOf('class="disclosure"')<700);
check('A no collection forms',!/<form\b/i.test(a));
check('B no collection forms',!/<form\b/i.test(b));
check('A no script or third party embedding',!/<script\b|<iframe\b/i.test(a));
check('B no script or third party embedding',!/<script\b|<iframe\b/i.test(b));
check('no active seller link in hub',!noSellerAnchor.test(hub));
check('hub four editorial streams',hub.includes('Perception &amp; attention')&&hub.includes('History of suggestion')&&hub.includes('Practice &amp; reflection')&&hub.includes('Tools under review'));
check('hub aria heading',hub.includes('aria-labelledby="fv-mind-title"'));
check('existing Fieldbook link on all variants',[a,b,hub].every(s=>s.includes('https://finalvestige.com/focus/')));
check('draft marked noindex',[a,b].every(s=>s.includes('name="robots" content="noindex,nofollow"')));
check('all variants responsive',[a,b,hub].every(s=>s.includes('@media(')));
check('reduced motion rules',[a,b,hub].every(s=>s.includes('prefers-reduced-motion')));
check('caption transcript present',b.includes('<strong>Transcript:</strong>'));
const captions=[...b.matchAll(/<strong>(\d\d):(\d\d)–(\d\d):(\d\d)<\/strong>/g)].map(m=>+m[1]*60 + +m[2]);const ends=[...b.matchAll(/<strong>(\d\d):(\d\d)–(\d\d):(\d\d)<\/strong>/g)].map(m=>+m[3]*60 + +m[4]);
check('exactly six caption sequences',captions.length===6);
check('caption starts at 0',captions[0]===0);
check('caption ends at 40',ends.at(-1)===40);
check('caption intervals contiguous',captions.every((t,i)=>i===0||t===ends[i-1]));
check('caption intervals positive',captions.every((t,i)=>ends[i]>t));
check('seller price not presented as fixed',[a,b].every(s=>!s.includes('$87.99')&&!s.includes('$37')));
check('plan includes no verified conversion claim',plan.includes('NOT COMPUTABLE')&&/zero approved affiliate links/i.test(plan));
check('plan has 3 creator mappings',plan.includes('Change Blindness')&&plan.includes('Mesmerism/Puységur')&&plan.includes('Attentional Blink'));
check('plan distinguishes seller click',plan.includes('An outbound click is not a commission'));
check('plan includes cohorts',plan.includes('7/30-day cohorts'));
check('plan prioritizes actual merchant evidence',plan.includes('settled merchant')&&plan.includes('qualified human'));
check('none of HTML contains merchant JS events',[a,b,hub].every(s=>!/<script\b|onclick\s*=|onload\s*=/i.test(s)));
return results;
}
const result=checks();
for (const r of result)test(r.label,()=>assert.ok(r.pass));
module.exports={checks};
