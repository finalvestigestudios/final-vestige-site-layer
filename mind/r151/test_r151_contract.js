'use strict';
// R151 read-only structural regression; Node: node mind/r151/test_r151_contract.js
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const dir=__dirname;
const art=fs.readFileSync(path.join(dir,'if-then-focus-investigation.md'),'utf8');
const memo=fs.readFileSync(path.join(dir,'one-offer-evidence-and-pilot.md'),'utf8');
const m=JSON.parse(fs.readFileSync(path.join(dir,'claim-authorization-matrix.json'),'utf8'));
let passed=0;function ok(v,msg){assert.ok(v,msg);passed++;}
ok(art.length>9500,'deep original investigation');
ok(art.includes('constructed illustration'),'illustration labeled');
ok(art.includes('94 independent tests'),'verified evidence statistic');
ok(art.includes('66 tests'),'mechanism qualified');
ok(art.includes('implementation intentions'),'scientific topic');
ok(art.includes('Puységur'),'archive bridge');
ok(art.includes('Seven Day Focus Fieldbook'),'existing resource');
ok(art.includes('https://finalvestige.com/focus/'),'first party focus link');
ok(!art.includes('awin1.com') && !art.includes('hop='),'no affiliate redirect');
ok(!/guaranteed (?:cure|concentration|income)/i.test(art),'no guaranteed benefits');
ok(m.sources.length>=12,'source ledger');
ok(m.claim_decisions.length>=20,'decision ledger');
ok(m.sources.some(x=>x.type==='regulator'),'FTC sources');
ok(m.sources.filter(x=>x.type==='academic').length>=5,'primary study sources');
ok(m.claim_decisions.find(x=>x.id==='C12').verdict==='NOT_VERIFIED','no acceptance claim');
ok(m.claim_decisions.find(x=>x.id==='C13').verdict==='REJECT','click is not commission');
ok(m.claim_decisions.find(x=>x.id==='C22').verdict==='NOT_COMPUTABLE','revenue not invented');
ok(Object.keys(m.release_gates).length>=20,'release gates defined');
ok(Object.values(m.release_gates).every(v=>v===false),'all gates closed');
ok(m.partner_approval==='UNVERIFIED','partner approval unknown');
ok(m.state==='UNPUBLISHED_HARD_HOLD','explicit hard hold');
ok(memo.includes('physically disabled button'),'commercial CTA must be inactive');
ok(memo.includes('If you purchase through this link'),'adjacent FTC disclosure template');
ok(memo.toLowerCase().includes('no scripts added'),'measurement uses existing systems');
ok(memo.includes('refund_or_chargeback'),'net refund deduction');
ok(memo.includes('merchant_confirmed_paid_order'),'merchant reconciliation');
ok(memo.includes('utm_content=verified_grok_asset_id'),'asset id unverified');
ok(memo.includes('NOT COMPUTABLE'),'missing data');
ok(memo.includes('variant'),'future A/B');
ok(memo.toLowerCase().includes('no autoplay'),'video optional');
ok(!/<script|<form|<iframe/i.test(memo),'no injected forms or scripts');
ok(!memo.includes('aff_id='),'no tracking affiliate URL');
console.log('R151 PASS '+passed+'/'+passed+' source-contract assertions');
