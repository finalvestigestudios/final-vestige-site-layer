'use strict';
const fs=require('node:fs');const path=require('node:path');
const root=__dirname;
function audit(files){
 const art=files['investigation.md'],html=files['page.wp.html'],claims=JSON.parse(files['claims.json']),plan=files['conversion-plan.md'],readme=files['README.md'];
 const out=[];const check=(name,test)=>{out.push({name,pass:Boolean(test)});};
 check('documented 1784 versus 1785 editions',/1784 French/.test(art)&&/1785 English/.test(art));
 check('historical analysis follows competing causes',/blindfold/i.test(art)&&/commission/i.test(art));
 check('specific Deslon vs Puységur limitation',/Deslon/.test(art)&&/Puységur/.test(art));
 check('not Franklin lone designer',/Lavoisier/.test(art)&&/collaborative/.test(art));
 check('substantive longform investigation',art.split(/\s+/).length>=1800);
 check('at least 10 sections',art.match(/^## /gm)?.length>=10);
 check('sources present with links',/gutenberg.org/.test(art)&&/wellcomecollection.org/.test(art)&&/jameslindlibrary.org/.test(art));
 check('full HTML includes article sections',html.match(/class="fv-section"/g)?.length>=10);
 check('single H1',html.match(/<h1\b/g)?.length===1);
 check('H1 meaningful',/<h1>The Blindfold Was the Evidence<\/h1>/.test(html));
 check('nav has accessible name',/aria-label="On this investigation"/.test(html));
 check('HTML document unique IDs',((a)=>a.length===new Set(a).size)([...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1])));
 check('all fragment links exist',([...html.matchAll(/href="#([^"]+)"/g)].every(m=>html.includes('id="'+m[1]+'"'))));
 check('readability 320px',/min\(100% - 32px,1080px\)/.test(html)&&/@media\(max-width:850px\)/.test(html));
 check('reduced motion',/prefers-reduced-motion:reduce/.test(html));
 check('keyboard focus visible',/:focus-visible/.test(html));
 check('details native interaction',/<details>/.test(html)&&/<summary>/.test(html));
 check('no scripts',!/<script\b/i.test(html));
 check('no forms or Jetpack duplication',!/<form\b|wp-block-jetpack-subscriptions/i.test(html));
 check('no merchant outbound href',!/<a\b[^>]+href="https?:\/\/(?:www\.)?(?:inspire3|hypnosislive|zen12|brainwaveshots|affiliates\.inspire3)\.com/i.test(html));
 check('affiliate disclosure adjacent to inert action',/fv-earn[\s\S]{0,550}fv-disabled/.test(html));
 check('no active buy link',!/<a\b[^>]*>(?:Buy|Purchase|Shop|Get Total Focus|Get Zen12)/i.test(html));
 check('no autoplay / embedded video / third-party',!/<video|<iframe|autoplay/i.test(html));
 check('commercial products in separate box',/fv-commercial/.test(html)&&/TOOLS UNDER REVIEW/.test(html));
 check('existing Focus linked',/href="https:\/\/finalvestige\.com\/focus\/"/.test(html));
 check('published Puységur linked',/href="https:\/\/finalvestige\.com\/free-resources\/puysegurs-animal-magnetism-files\/"/.test(html));
 check('safety: exercise not clinical test',/not a diagnostic test/i.test(html));
 check('sources encoded/valid URL',claims.sources.length>=15&&claims.sources.every(s=>/^https:\/\//.test(s.url)));
 check('all claims have source IDs',claims.claims.length>=30&&claims.claims.every(c=>c.source_ids.length>0));
 check('all claim refs resolve',claims.claims.every(c=>c.source_ids.every(id=>claims.sources.some(s=>s.id===id))));
 check('offer exact format in ledger',claims.claims.some(c=>/33-minute 47-MB/.test(c.claim)));
 check('claims reject unsupported efficacy',claims.claims.some(c=>/reprograms brain/.test(c.claim)&&/reject/i.test(c.disposition)));
 check('Zen12 equivalence rejected',claims.claims.some(c=>/twelve minutes equals an hour/.test(c.claim)&&/reject/i.test(c.disposition)));
 check('partner approval false',claims.partner.account_approved===false&&claims.partner.affiliate_url===null);
 check('outbound activity false',claims.partner.active_merchant_cta===false);
 check('no invented prices / payout',claims.partner.commission_rate===null&&claims.partner.product_price_approved===null);
 check('approval & email rights unverified',claims.partner.email_channel_permission===false&&!claims.partner.tracking_terms_approved);
 check('no live route implied',/NOT live/.test(plan));
 check('single Jetpack preserved',/single existing Jetpack opt-in/.test(plan));
 check('privacy attribution off by default',/currently OFF/.test(plan));
 check('privacy explicitly forbids identifiers',/Exclude user ID, IP, UA, full referrer/.test(plan));
 check('no statistical conversion promise',/do not call a winner/i.test(plan));
 check('optional film hypothesis',/A=text-only/.test(plan)&&/B=identical/.test(plan));
 check('video no autoplay/no-JS',/no autoplay/.test(plan)&&/without JS/.test(plan));
 check('release hold',/Release \*\*HOLD\*\*/.test(plan));
 check('dispatch coordination',/Issue #174/.test(plan));
 check('homepage isolation',/PR #49/.test(readme)&&/Issue #150/.test(readme));
 check('readme instructions',/node mind\/mesmer-franklin-r11\/qa.cjs/.test(readme));
 return out;
}
function execute(){
 const filenames=['investigation.md','page.wp.html','claims.json','conversion-plan.md','README.md'];
 const files=Object.fromEntries(filenames.map(f=>[f,fs.readFileSync(path.join(root,f),'utf8')]));
 const results=audit(files);for(const x of results)console.log((x.pass?'PASS':'FAIL')+' '+x.name);
 const failures=results.filter(x=>!x.pass);console.log(results.length-failures.length+'/'+results.length+' PASS');if(failures.length)process.exitCode=1;
}
if(require.main===module)execute();
module.exports={audit};
