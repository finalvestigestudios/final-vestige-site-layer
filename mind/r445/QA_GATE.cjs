check('no absolute merchant outbound in HTML',()=>[A,B,H].forEach(x=>sourceGuard(x)));
check('static works without JavaScript',()=>[A,B,H].forEach(x=>assert.ok(!/<script\b|<noscript\b/i.test(x))));
check('SVG with accessible label',()=>assert.ok(/<svg[^>]*role="img"[^>]*aria-labelledby/.test(B)));
check('film captions file linked',()=>assert.ok(B.includes('./R445_OPTIONAL_42S.vtt')));
check('source named offer pages exist as text',()=>{assert.ok(A.includes('zen12.com/about'));assert.ok(A.includes('zen12.com/secret/'));});
check('disclosure not only footer',()=>{assert.ok(A.indexOf('commission-disclosure')<A.indexOf('</main>'));});
check('Source linked editorial standards',()=>assert.ok(H.includes('editorial-standards/')));
check('R445 source-controlled noindex',()=>[A,B,H].forEach(x=>assert.ok(x.includes('noindex,nofollow'))));
const saved=[A,B,H];const reject=(name,modify,guard=offerGuard)=>check('adversarial '+name,()=>{let rejected=false;try{guard(modify(A));}catch{rejected=true;}assert.ok(rejected,'unsafe mutation bypassed guard');});
reject('active merchant earning href',s=>s.replace('</main>','<a href="https://zen12.com/offer?ref=unverified">BUY</a></main>'));
