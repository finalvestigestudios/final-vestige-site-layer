function check(label,fn){try{fn();total++;process.stdout.write('PASS '+label+'\n');}catch(e){throw Error('FAIL '+label+': '+e.message);}}
const buyer=html=>{let t=html.match(/<section aria-labelledby="question">([\s\S]*?)<\/main>/i);assert.ok(t,'missing common buyer body');return t[1];};
const sourceGuard=(html)=>{
 assert.ok(!/<script\b/i.test(html),'script tag');
 assert.ok(!/<iframe\b/i.test(html),'iframe');
 assert.ok(!/<form\b/i.test(html),'second form');
 assert.ok(!/<(?:img|video|audio)[^>]+src=["']https?:/i.test(html),'external media');
 assert.ok(!/\bonclick\s*=|onload\s*=|onerror\s*=/i.test(html),'event handlers');
 assert.ok(!/<(?:video|audio)\b[^>]*\bautoplay\b/i.test(html),'autoplay attribute');
 assert.ok(!/\bdata:\s*text\/html/i.test(html),'data html');
 assert.ok(!/<a\b[^>]*href\s*=\s*["'](?:https?:)?\/\/(?:www\.)?(?:zen12\.com|inspire3\.com|affiliates\.inspire3\.com|hypnosislive\.com|brainwaveshots\.com)/i.test(html),'active merchant link');
 assert.ok(!/\b(?:gtag\(|fbq\(|_paq|analytics\.js|google-analytics|doubleclick|collect\?)/i.test(html),'tracking/pixel script');
 assert.ok(!/target=["']_blank["']/i.test(html),'external new-tab context');
 assert.ok(!/http-equiv=["']refresh/i.test(html),'redirect');
};
function offerGuard(html){
 sourceGuard(html);
 assert.ok(/<html lang="en">/.test(html),'lang');
 assert.ok(/<main id="main">/.test(html),'main');
 assert.ok(/href="#main"/.test(html),'skip');
 assert.ok(/name="viewport"/.test(html),'viewport');
 assert.ok(/prefers-reduced-motion/.test(html),'reduced motion');
 assert.ok(/noindex,nofollow/.test(html),'no indexing');
 const button=html.match(/<button\b[^>]*class="disabled-offer"[^>]*>/);
 assert.ok(button,'offer button absent');
 assert.ok(/\sdisabled(?=\s|>|=)/.test(button[0]),'offer button not natively disabled');
 assert.ok(/type="button"/.test(button[0]),'offer button submitting');
 assert.ok(/aria-describedby="commission-disclosure release-reason"/.test(button[0]),'missing describedby');
 assert.ok(/id="commission-disclosure"/.test(html),'adjacent disclosure absent');
 assert.ok(/may earn a commission at no additional cost to you/.test(html),'plain earning relationship absent');
 assert.ok(/No affiliate link is currently active/.test(html),'inactive condition missing');
 assert.ok(!/guaranteed\s+(?:focus|wealth|income|healing|cure)/i.test(html),'unqualified benefit promise');
 assert.ok(html.indexOf('id="commission-disclosure"')<html.indexOf('class="disabled-offer"'),'disclosure not before offer');
 assert.ok(html.indexOf('class="disabled-offer"')-html.indexOf('id="commission-disclosure"')<750,'disclosure too distant');
 assert.ok(!/\b(?:\$\d+[\.,]?\d*|[0-9]+%\s*(?:off|commission)|guaranteed\s+(?:wealth|income|focus|cure))/i.test(html),'unsupported hard commercial numeric/guarantee');
 assert.ok(html.includes('https://finalvestige.com/focus/'),'existing free funnel missing');
 assert.ok(html.includes('https://finalvestige.com/2026/11/02/change-blindness/'),'canonical article missing');
 assert.ok(!/type=["']email["']/.test(html),'duplicate email capture');
 assert.ok(!/hidden|display\s*:\s*none/i.test(html.slice(html.indexOf('<section class="decision"'))),'hidden offer');
}
check('source UTF-8 files load',()=>assert.ok(I.length>15000&&A.length>7000&&B.length>A.length&&H.length>4000));
for (const [name,value] of [['buyer A',A],['buyer B',B]])check('source and commercial safety '+name,()=>offerGuard(value));
check('source and nav safety hub',()=>sourceGuard(H));
