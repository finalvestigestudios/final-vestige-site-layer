check('B optional details, poster and transcript',()=>{assert.ok(B.includes('<details class="film">'));assert.ok(B.includes('class="poster"'));assert.ok(B.includes('transcript'));assert.ok(!B.includes('<video'));});
check('VTT six timed cues',()=>{assert.ok(V.startsWith('WEBVTT'));assert.equal((V.match(/-->/g)||[]).length,6);assert.ok(V.includes('00:00:42.000'));});
check('hub four streams',()=>assert.equal((H.match(/class="stream"/g)||[]).length,4));
check('hub one existing optional route',()=>assert.ok(H.includes('https://finalvestige.com/focus/')));
check('hub no live vendor CTA',()=>sourceGuard(H));
check('hub no new top-level WP category',()=>assert.ok(H.includes('no live category, menu or homepage changes')));
check('matrix 34 decisions',()=>assert.equal(M.claims.length,34));
check('matrix 18 source links',()=>assert.equal(Object.keys(M.sources).length,18));
check('matrix all claim evidence links',()=>M.claims.forEach(c=>{assert.ok(c.id&&c.classification&&c.source_url&&c.decision);assert.equal(c.source_url,M.sources[c.source_id]);}));
check('matrix 28 held release gates',()=>{assert.equal(M.release_gates.length,28);assert.ok(M.release_gates.every(g=>g.release_state==='HOLD'&&g.pass_evidence===null));});
check('partner not asserted approved',()=>assert.ok(M.accounts.verification.includes('no named FV acceptance')));
check('product-specific efficacy not passed',()=>{assert.ok(M.claims.some(x=>x.id==='M005'&&x.decision.startsWith('OMIT')));assert.ok(M.policy.independent_science_not_brand_trial);});
check('buyer exposes no guaranteed clinical claim',()=>{assert.ok(!/guarantees? you|clinically proven Zen12|cures? anxiety/i.test(A+B));});
check('no pretend completed video',()=>assert.ok(B.includes('there is no encoded audio/video')));
check('article primary scientific sources',()=>['16210542','20637455','23593244'].forEach(t=>assert.ok(I.includes(t))));
check('article Puységur source trail',()=>assert.ok(I.includes('puysegurs-animal-magnetism-files')));
check('article no affiliate checkout or tracked merchant referral',()=>assert.ok(!/\]\(https?:\/\/(?:www\.)?(?:zen12|hypnosislive|brainwaveshots)[^)]*[?&](?:ref|aff|affiliate|hop)=/i.test(I)));
check('acceptance counts settlement not click',()=>{assert.ok(C.includes('merchant_paid_order'));assert.ok(C.includes('merchant_commission_settled'));assert.ok(C.includes('NOT COMPUTABLE'));});
