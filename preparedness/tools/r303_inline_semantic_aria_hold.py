#!/usr/bin/env python3
"""R303: fail-closed inline-semantic and ARIA fidelity for Preparedness article drafts.

Read-only safety/integration gate, subordinate to an exact-byte-pinned R302
predecessor. It cannot publish, certify medical guidance, verify browsers, or
approve sales. DRAFT_HARD_HOLD is a *review state*, not a PASS/release state.

R302 tracked blocks, tables and source-to-claim citations, but did not represent
inline <strong>, <em>, <span> etc. This gate closes that explicitly bounded gap.
Author-authored anchor tags are NOT checked here because the native builder also
creates links for {{link:...}} tokens; earlier exact native-export checks remain
necessary for anchor href fidelity. JS/CSS/browser rendering remain unreviewed.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
from typing import Any

PREDECESSOR = 'preparedness/tools/r302_semantic_structure_citation_context_hold.py'
PREDECESSOR_OID = '2fa1a9d8818cceac546557ff303f7e9776de5ea7'
CUSTODY = 'preparedness/audits/r200_seven_cluster_35_article_frozen_custody.json'
CUSTODY_OID = '5822f9dfde21d1f3bdfc26658769d852c639438c'
# Textual significance and inline accessibility attributes can change while the
# flattened copy, source counts and block-level event sequence remain identical.
INLINE = frozenset(('strong', 'em', 'span', 'b', 'i', 'mark', 'small',
    'abbr', 'time', 'q', 'cite', 'sub', 'sup', 'u', 's', 'del', 'ins',
    'bdi', 'bdo', 'data', 'ruby', 'rt', 'rp', 'kbd', 'samp', 'var', 'wbr'))
INLINE_VOID = frozenset(('wbr',))
# HTMLParser passes a slash-terminated void tag to handle_startendtag(),
# although the same HTML element may be written <wbr> or <wbr/>.
# Both serialize to one void event; only an explicit </wbr> is rejected.
BOOLEAN_INLINE_ATTRIBUTES = frozenset(('hidden', 'inert', 'itemscope'))
SLUG = re.compile(r'[a-z0-9]+(?:-[a-z0-9]+)*\Z')


def git_blob(data: bytes) -> str:
    return hashlib.sha1(b'blob '+str(len(data)).encode('ascii')+b'\0'+data).hexdigest()


def safe_file(root: Path, relative: str) -> bool:
    try:
        base = root.absolute()
        path = (base / relative).absolute()
        if not path.is_relative_to(base) or not path.is_file():
            return False
        while path != base:
            if path.is_symlink():
                return False
            path = path.parent
        return True
    except (OSError, ValueError, RuntimeError):
        return False


def load_predecessor(root: Path):
    if not safe_file(root, PREDECESSOR):
        raise ValueError('PINNED_R302_PREDECESSOR_MISSING_OR_SYMLINK')
    if git_blob((root / PREDECESSOR).read_bytes()) != PREDECESSOR_OID:
        raise ValueError('PINNED_R302_PREDECESSOR_CHANGED')
    spec = importlib.util.spec_from_file_location('fv_r303_pinned_r302', root / PREDECESSOR)
    if spec is None or spec.loader is None:
        raise RuntimeError('PINNED_R302_IMPORT_UNAVAILABLE')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def inline_compare(source: str, export: str, predecessor: Any) -> list[str]:
    """Independent ordered inline events layered over R302's existing events.

    Citation superscripts generated by the builder remain handled by the exact
    R302 citation parser; ordinary authored <sup> tags are preserved here.
    """
    class InlineSemantic(predecessor.Semantic):
        def handle_starttag(self, tag, attrs):
            if (tag not in INLINE or not self.active or self.skip_stack or self.cite
                or (self.mode == 'export' and tag == 'sup'
                    and 'pa-cite' in (dict(attrs).get('class') or '').split())):
                return super().handle_starttag(tag, attrs)
            # HTMLParser preserves duplicate and valueless attributes. A match
            # between two equally malformed tags cannot constitute safe parity.
            names = [name for name, _ in attrs]
            if len(names) != len(set(names)):
                self.errors.append('INLINE_DUPLICATE_ATTRIBUTE:' + tag)
            for name, value in attrs:
                if value is None and name not in BOOLEAN_INLINE_ATTRIBUTES:
                    self.errors.append('INLINE_VALUELESS_ATTRIBUTE:' + tag + ':' + name)
            # All attrs matter: ARIA, role, lang, class, style, hidden, title etc.
            self._event('open', tag, tuple(sorted(attrs)))
            if tag not in INLINE_VOID:
                self.structure.append(tag)
            else:
                self._event('close', tag)

        def handle_startendtag(self, tag, attrs):
            # The R302 parent special-cases only its own block-level VOID set.
            # A slash on an R303 inline void such as <wbr/> would otherwise
            # dispatch an additional handle_endtag('wbr'), falsely marking a
            # fully intact source/export as INLINE_VOID_CLOSED. Preserve the
            # event stream of <wbr> without allowing a literal </wbr>.
            if tag in INLINE_VOID:
                self.handle_starttag(tag, attrs)
                return
            return super().handle_startendtag(tag, attrs)

        def handle_endtag(self, tag):
            if tag not in INLINE or not self.active or self.skip_stack or self.cite:
                return super().handle_endtag(tag)
            if tag in INLINE_VOID:
                self.errors.append('INLINE_VOID_CLOSED:' + tag)
                return
            self._event('close', tag)
            if not self.structure or self.structure[-1] != tag:
                self.errors.append('INLINE_STRUCTURE_UNBALANCED:' + tag)
            else:
                self.structure.pop()

    src = InlineSemantic('source')
    dst = InlineSemantic('export')
    src.feed(source)
    dst.feed(export)
    left = src.finish()
    right = dst.finish()
    issues = list(src.errors) + list(dst.errors)
    left_inline = [e for e in left if e[0] in ('open', 'close') and len(e) > 1 and e[1] in INLINE]
    right_inline = [e for e in right if e[0] in ('open', 'close') and len(e) > 1 and e[1] in INLINE]
    if left_inline != right_inline:
        issues.append('INLINE_MARKUP_OR_ARIA_DRIFT')
    if left != right and left_inline == right_inline:
        issues.append('INLINE_SCOPE_OR_CITATION_CONTEXT_DRIFT')
    # Never use this narrower gate to suppress existing block/citation failures.
    issues.extend(predecessor.compare(source, export))
    return sorted(set(issues))


def audit(root: Path, custody: dict, predecessor: Any, previous: dict | None = None) -> dict:
    errors = []
    matches = 0
    rows = custody.get('articles') if isinstance(custody, dict) else None
    if not isinstance(rows, list) or len(rows) != 35:
        errors.append('AUTHENTIC_35_ARTICLE_CUSTODY_MISSING')
        rows = []
    slugs = set()
    for row in rows:
        slug = row.get('slug') if isinstance(row, dict) else None
        if not isinstance(slug, str) or not SLUG.fullmatch(slug):
            errors.append('INVALID_ARTICLE_SLUG')
            continue
        if slug in slugs:
            errors.append('DUPLICATE_ARTICLE_SLUG:' + slug)
            continue
        slugs.add(slug)
        inp = f'preparedness/content/articles/{slug}.body.html'
        out = f'preparedness/build/wp/{slug}.html'
        if not safe_file(root, inp):
            errors.append('AUTHORED_BODY_MISSING_OR_SYMLINK:' + slug)
            continue
        if not safe_file(root, out):
            errors.append('WORDPRESS_DRAFT_MISSING_OR_SYMLINK:' + slug)
            continue
        try:
            src = (root / inp).read_text(encoding='utf-8')
            dst = (root / out).read_text(encoding='utf-8')
            diffs = inline_compare(src, dst, predecessor)
            errors.extend(error + ':' + slug for error in diffs)
            if not diffs:
                matches += 1
        except (OSError, UnicodeError, RuntimeError, ValueError) as exc:
            errors.append('UNREADABLE_ARTICLE:' + slug + ':' + type(exc).__name__)
    if len(slugs) != 35:
        errors.append('35_ARTICLE_SLATE_INCOMPLETE')
    if previous is not None and (
        not isinstance(previous, dict)
        or previous.get('state') != 'DRAFT_HARD_HOLD'
        or previous.get('errors') != []
        or previous.get('article_semantic_matches') != 35
        or previous.get('publication_authorized') is not False
        or previous.get('independent_qd_pass') is not False
        or previous.get('medical_safety_verified') is not False
        or previous.get('privacy_verified') is not False
        or previous.get('all_41_exports_independently_approved') is not False
    ):
        errors.append('R302_PREDECESSOR_NOT_RECONCILED')
    return {
        'schema': 'fv-preparedness-r303-inline-semantic-aria-fidelity-hold-v1',
        'state': 'INVALID_HARD_HOLD' if errors else 'DRAFT_HARD_HOLD',
        'errors': sorted(set(errors)),
        'article_inline_semantic_matches': matches,
        'r302_pinned_and_required': True,
        'source_and_citation_truth_verified': False,
        'browser_css_accessibility_qa_verified': False,
        'tool_104_emergency_privacy_print_review_approved': False,
        '14_body_lineage_reconciled': False,
        '12_metadata_lineage_reconciled': False,
        'seven_contributor_branches_require_fresh_review': True,
        'all_41_exports_independently_approved': False,
        'independent_human_approval': False,
        'publication_authorized': False,
        'independent_qd_pass': False,
        'medical_safety_verified': False,
        'privacy_verified': False,
        'merchant_approved': False,
        'confirmed_paid_orders': None,
        'realized_net_revenue_per_1000_qualified_sessions': None,
    }


def run(root: Path) -> dict:
    predecessor = load_predecessor(root)
    if not safe_file(root, CUSTODY) or git_blob((root / CUSTODY).read_bytes()) != CUSTODY_OID:
        raise ValueError('PINNED_R200_CUSTODY_MISSING_OR_CHANGED')
    custody = json.loads((root / CUSTODY).read_bytes())
    # R302.run runs the exact R301/R300/.../native source-and-export chain.
    upstream = predecessor.run(root)
    return audit(root, custody, predecessor, upstream)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo-root', type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args(argv)
    try:
        result = run(args.repo_root)
    except (OSError, UnicodeError, ValueError, KeyError, TypeError, RuntimeError, ImportError) as exc:
        result = {
            'schema': 'fv-preparedness-r303-inline-semantic-aria-fidelity-hold-v1',
            'state': 'INVALID_HARD_HOLD',
            'errors': ['AUTHENTIC_REPOSITORY_OR_BUILD_UNAVAILABLE:' + type(exc).__name__],
            'publication_authorized': False, 'independent_qd_pass': False,
            'medical_safety_verified': False, 'privacy_verified': False,
            'all_41_exports_independently_approved': False,
        }
    print(json.dumps(result, indent=2, sort_keys=True))
    # Neither review-only state is a successful release exit code.
    return 2 if result['state'] == 'DRAFT_HARD_HOLD' else 1


if __name__ == '__main__':
    raise SystemExit(main())
