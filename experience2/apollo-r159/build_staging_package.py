#!/usr/bin/env python3
"""R159 deterministic CSP/SRI staging package derived from byte-pinned R158 source.

May rebuild R158 from repository (canonical), or use an independently verified
R158 ZIP generated by that builder (for hermetic offline testing). No writes to WP.
"""
import argparse
import base64
import hashlib
import importlib.util
import json
import tempfile
import zipfile
from pathlib import Path

ORIGINAL_ZIP_SHA256 = '8d7cef94b83917fa6b8eb555e1b2a077cafd324e1d7372a5ac5d4433a753c0c2'
STAMP = (1980,1,1,0,0,0)

def sha(content): return hashlib.sha256(content).hexdigest()

def zip_bytes(path):
    data = Path(path).read_bytes()
    if sha(data) != ORIGINAL_ZIP_SHA256:
        raise ValueError('R158 verified base package SHA-256 mismatch')
    with zipfile.ZipFile(path) as z:
        names = {
            'templates/ledger.html': 'fv-apollo-r158/templates/ledger.html',
            'assets/research-desk.css': 'fv-apollo-r158/assets/research-desk.css',
            'assets/research-desk.js': 'fv-apollo-r158/assets/research-desk.js',
        }
        return {k:z.read(v) for k,v in names.items()}

def build(out, stub_path, repo=None, r158_zip=None):
    out = Path(out); stub_path=Path(stub_path)
    if (repo is None) == (r158_zip is None):
        raise ValueError('specify exactly one of --repo or --r158-zip')
    if repo:
        source=Path(repo)/'experience2/apollo-r158/build_staging_package.py'
        spec=importlib.util.spec_from_file_location('apollo_r158_builder',str(source))
        module=importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        with tempfile.TemporaryDirectory() as tmp:
            generated=module.build(repo, tmp)
            entries=zip_bytes(generated)
    else:
        entries=zip_bytes(r158_zip)
    stub=stub_path.read_text(encoding='utf-8')
    for k,p in [('HTML','templates/ledger.html'),('CSS','assets/research-desk.css'),('JS','assets/research-desk.js')]:
        token='@@'+k+'_SHA256@@'
        if stub.count(token)!=1: raise ValueError('missing or duplicated '+token)
        stub=stub.replace(token,sha(entries[p]))
    entries['fv-apollo-research-desk.php']=stub.encode('utf-8')
    manifest={
        'release':'STAGING_HOLD_NOT_LIVE',
        'derived_r158_zip_sha256':ORIGINAL_ZIP_SHA256,
        'assets':{k:{'sha256':sha(v),'sri':'sha256-'+base64.b64encode(hashlib.sha256(v).digest()).decode('ascii')} for k,v in sorted(entries.items())},
        'axe':'NOT_EXECUTED_BY_BUILD',
        'wp_staging':'NOT_INSTALLED',
        'media_commercial_rights':'NOT_CLEARED',
        'verified_commercial_sku':'NONE',
        'csp_review':'STAGING_POLICY_SELF_TEST_ONLY',
        'analytics':'NONE_ADDED',
    }
    entries['evidence/MANIFEST.json']=(json.dumps(manifest,sort_keys=True,indent=2)+'\n').encode()
    out.mkdir(parents=True,exist_ok=True)
    package=out/'fv-apollo-r159-wordpress-staging.zip'
    with zipfile.ZipFile(package,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for name,value in sorted(entries.items()):
            zi=zipfile.ZipInfo('fv-apollo-r159/'+name,STAMP)
            zi.compress_type=zipfile.ZIP_DEFLATED
            zi.external_attr=0o644<<16
            z.writestr(zi,value,compress_type=zipfile.ZIP_DEFLATED,compresslevel=9)
    receipt={**manifest,'zip_sha256':sha(package.read_bytes()),'zip_bytes':package.stat().st_size}
    (out/'build_receipt.json').write_text(json.dumps(receipt,sort_keys=True,indent=2)+'\n')
    print(json.dumps({'zip_sha256':receipt['zip_sha256'],'zip_bytes':receipt['zip_bytes'],'paths':len(entries)},sort_keys=True))
    return package

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--repo')
    p.add_argument('--r158-zip')
    p.add_argument('--out',required=True)
    p.add_argument('--stub',default=str(Path(__file__).with_name('wordpress-staging-adapter.stub.php')))
    a=p.parse_args()
    build(a.out,a.stub,repo=a.repo,r158_zip=a.r158_zip)
