/** The opt-in is mandatory even on a staging site. Never fallback to WP_DEBUG. */
function fv_ex2_apollo_sealed_allowed() {
    return defined('FV_EX2_APOLLO_STAGING_ALLOW') && FV_EX2_APOLLO_STAGING_ALLOW === true
        && function_exists('wp_get_environment_type')
        && in_array(wp_get_environment_type(), array('staging', 'development', 'local'), true)
        && function_exists('is_user_logged_in') && is_user_logged_in()
        && function_exists('current_user_can') && current_user_can('edit_pages');
}

/** Decompression is bounded by the exact generated byte size and SHA-256 checksum. */
function fv_ex2_apollo_sealed_asset($name) {
    if (!is_string($name) || !array_key_exists($name, FV_EX2_APOLLO_PACKED)
        || !array_key_exists($name, FV_EX2_APOLLO_SHA256)
        || !array_key_exists($name, FV_EX2_APOLLO_LENGTHS)) { return false; }
    $data = base64_decode(FV_EX2_APOLLO_PACKED[$name], true);
    if ($data === false) { return false; }
    $expected_len = FV_EX2_APOLLO_LENGTHS[$name];
    if (!is_int($expected_len) || $expected_len < 1 || $expected_len > 500000) { return false; }
    $raw = @gzuncompress($data, $expected_len + 1);
    if (!is_string($raw) || strlen($raw) !== $expected_len
        || !hash_equals(FV_EX2_APOLLO_SHA256[$name], hash('sha256', $raw))) { return false; }
    return $raw;
}

/** Optional shortcode creates only a private iframe; no plugin generated/ files. */
function fv_ex2_apollo_sealed_shortcode($attrs = array()) {
    if (!fv_ex2_apollo_sealed_allowed()) { return ''; }
    $nonce = wp_create_nonce('fv_ex2_apollo_sealed');
    $url = add_query_arg(array(
        'action' => 'fv_ex2_apollo_sealed_page',
        '_wpnonce' => $nonce,
    ), admin_url('admin-ajax.php'));
    return '<section class="fv-ex2-apollo-review" aria-label="Private Apollo 1 research staging">'
        . '<p role="note"><strong>PRIVATE STAGING STUDY — NOT PUBLISHED.</strong> '
        . 'NASA source references are informational and do not imply NASA endorsement.</p>'
        . '<iframe src="' . esc_url($url) . '" '
        . 'title="Apollo 1 investigation — private, source-grounded Research Desk preview" '
        . 'sandbox="allow-scripts allow-popups allow-popups-to-escape-sandbox allow-downloads" loading="lazy" '
        . 'referrerpolicy="no-referrer" '
        . 'style="display:block;width:100%;min-height:80vh;border:1px solid #8c7958;background:#0c1010"></iframe>'
        . '<p class="fv-ex2-apollo-review__alternate"><a href="' . esc_url($url) . '" '
        . 'target="_blank" rel="noopener noreferrer" referrerpolicy="no-referrer">'
        . 'Open the private full-page evidence review</a> for narrow screens or assistive technologies. '
        . 'This URL requires your current editor session and a valid nonce.</p>'
        . '<p><a href="https://finalvestige.com/2026/08/20/the-hatch-opened-inward-apollo-1/">'
        . 'Read the published investigation</a></p>'
        . '</section>';
}
add_shortcode('fv_ex2_apollo_sealed_preview', 'fv_ex2_apollo_sealed_shortcode');

function fv_ex2_apollo_sealed_validate_request() {
    if (!fv_ex2_apollo_sealed_allowed()) { status_header(403); exit; }
    check_ajax_referer('fv_ex2_apollo_sealed');
}

/** No privileged action is registered under wp_ajax_nopriv_*. */
function fv_ex2_apollo_sealed_page() {
    fv_ex2_apollo_sealed_validate_request();
    // Check everything before sending HTML. Never show a partially verified exhibit.
    $fragment = fv_ex2_apollo_sealed_asset('fragment.html');
    $css = fv_ex2_apollo_sealed_asset('apollo.css');
    $js = fv_ex2_apollo_sealed_asset('apollo.js');
    if (!is_string($fragment) || !is_string($css) || !is_string($js)
        || strpos($fragment, 'id="documentary-trails"') === false
        || strpos($fragment, 'id="atlas"') === false
        || substr_count($fragment, '{{FV_EX2_ASSET_BASE}}') !== 4) {
        status_header(503); exit;
    }
    $nonce = wp_create_nonce('fv_ex2_apollo_sealed');
    $base = admin_url('admin-ajax.php');
    foreach (array('evidence-export.csv', 'evidence-export.json',
                   'response-export.csv', 'response-export.json') as $file) {
        if (fv_ex2_apollo_sealed_asset($file) === false) { status_header(503); exit; }
        $placeholder = '{{FV_EX2_ASSET_BASE}}/' . $file;
        if (substr_count($fragment, $placeholder) !== 1) { status_header(503); exit; }
        $url = add_query_arg(array('action' => 'fv_ex2_apollo_sealed_download',
            'file' => $file, '_wpnonce' => $nonce), $base);
        $fragment = str_replace($placeholder, esc_url($url), $fragment);
    }
    if (strpos($fragment, '{{FV_EX2_ASSET_BASE}}') !== false
        || preg_match('~<\s*(?:script|style|img|iframe|main|html|body)\b~i', $fragment)) {
        status_header(503); exit;
    }
    $csp_nonce = base64_encode(random_bytes(18));
    nocache_headers();
    header('Content-Type: text/html; charset=UTF-8');
    header('X-Robots-Tag: noindex, nofollow, noarchive');
    header('X-Content-Type-Options: nosniff');
    header('Referrer-Policy: no-referrer');
    header("Content-Security-Policy: default-src 'none'; script-src 'nonce-{$csp_nonce}'; style-src 'nonce-{$csp_nonce}'; img-src 'none'; font-src 'none'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'self'");
    echo '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
        . '<title>Private Apollo 1 Evidence Review — Final Vestige</title>'
        . '<meta name="robots" content="noindex,nofollow"><style nonce="' . $csp_nonce . '">'
        . $css . "\n.fv-ex2-apollo__review-h1{position:absolute;width:1px;height:1px;overflow:hidden;clip-path:inset(50%);white-space:nowrap}"
        . '</style></head><body>'
        . '<section class="fv-ex2-apollo" aria-label="Apollo 1 evidence investigation">'
        . '<h1 class="fv-ex2-apollo__review-h1">Apollo 1: Research Desk and primary-source casefile</h1>'
        . $fragment . '</section><script nonce="' . $csp_nonce . '">'
        . str_replace('</script', '<\\/script', $js) . '</script></body></html>';
    exit;
}
add_action('wp_ajax_fv_ex2_apollo_sealed_page', 'fv_ex2_apollo_sealed_page');

function fv_ex2_apollo_sealed_download() {
    fv_ex2_apollo_sealed_validate_request();
    $files = array(
        'evidence-export.csv' => 'text/csv; charset=UTF-8',
        'evidence-export.json' => 'application/json; charset=UTF-8',
        'response-export.csv' => 'text/csv; charset=UTF-8',
        'response-export.json' => 'application/json; charset=UTF-8',
    );
    $file = isset($_GET['file']) && is_string($_GET['file']) ? $_GET['file'] : '';
    if (!array_key_exists($file, $files)) { status_header(404); exit; }
    $raw = fv_ex2_apollo_sealed_asset($file);
    if (!is_string($raw)) { status_header(503); exit; }
    nocache_headers();
    header('X-Robots-Tag: noindex, nofollow, noarchive');
    header('X-Content-Type-Options: nosniff');
    header('Cache-Control: no-store, private');
    header('Content-Type: ' . $files[$file]);
    header('Content-Disposition: attachment; filename="apollo-' . $file . '"');
    header('Content-Length: ' . strlen($raw));
    echo $raw;
    exit;
}
add_action('wp_ajax_fv_ex2_apollo_sealed_download', 'fv_ex2_apollo_sealed_download');
