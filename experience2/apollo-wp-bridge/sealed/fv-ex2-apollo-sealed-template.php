function fv_ex2_apollo_sealed_validate_request() {
    // Real WP check_ajax_referer() with its default $stop=true emits "-1" on failure.
    // This editor-only evidence endpoint instead guarantees an empty, uncached 403.
    // Explicit _wpnonce avoids precedence from an unrelated _ajax_nonce parameter.
    nocache_headers();
    if (!fv_ex2_apollo_sealed_allowed()) { status_header(403); exit; }
    $nonce = $_REQUEST['_wpnonce'] ?? null;
    if (!is_string($nonce) || strlen($nonce) < 1 || strlen($nonce) > 128) {
        status_header(403); exit;
    }
    $verified = check_ajax_referer('fv_ex2_apollo_sealed', '_wpnonce', false);
    // A 12–24h old WordPress nonce returns 2: still valid per WordPress core.
    if ($verified !== 1 && $verified !== 2) { status_header(403); exit; }
}

/** No privileged action is registered under wp_ajax_nopriv_*. */
function fv_ex2_apollo_sealed_page() {
    fv_ex2_apollo_sealed_validate_request();
    // Check everything before sending HTML. Never show a partially verified exhibit.
    $fragment = fv_ex2_apollo_sealed_asset('fragment.html');
    $css = fv_ex2_apollo_sealed_asset('apollo.css');
    $js = fv_ex2_apollo_sealed_asset('apollo.js');
    $concordance = fv_ex2_apollo_sealed_asset('source-concordance.html');
    $concordance_css = fv_ex2_apollo_sealed_asset('source-concordance.css');
    $context_index = fv_ex2_apollo_sealed_asset('source-context.json');
    if (!is_string($fragment) || !is_string($css) || !is_string($js)
        || !is_string($concordance) || !is_string($concordance_css) || !is_string($context_index)
        || substr_count($concordance, 'data-concordance-record=') !== 6
        || substr_count($concordance, '{{FV_EX2_CONTEXT_EXPORT}}') !== 1
        || substr_count($concordance, 'type="radio"') !== 4
        || strpos($fragment, 'id="documentary-trails"') === false
        || strpos($fragment, 'id="atlas"') === false
        || substr_count($fragment, '{{FV_EX2_ASSET_BASE}}') !== 4) {
        status_header(503); exit;
    }
    $nonce = wp_create_nonce('fv_ex2_apollo_sealed');
    $base = admin_url('admin-ajax.php');
    foreach (array('evidence-export.csv', 'evidence-export.json',
                   'response-export.csv', 'response-export.json') as $file) {
        if (fv_ex2_apollo_sealed_asset($file) === false) { status_header(503); exit; }
        $placeholder = '{{FV_EX2_ASSET_BASE}}/' . $file;
        if (substr_count($fragment, $placeholder) !== 1) { status_header(503); exit; }
        $url = add_query_arg(array('action' => 'fv_ex2_apollo_sealed_download',
            'file' => $file, '_wpnonce' => $nonce), $base);
        $fragment = str_replace($placeholder, esc_url($url), $fragment);
    }
    if (strpos($fragment, '{{FV_EX2_ASSET_BASE}}') !== false
        || preg_match('~<\s*(?:script|style|img|iframe|main|html|body)\b~i', $fragment)) {
        status_header(503); exit;
    }
    // Derived JSON index uses the same editor/nonce-guarded route as the canonical exports.
    $context_url = add_query_arg(array('action' => 'fv_ex2_apollo_sealed_download',
        'file' => 'source-context.json', '_wpnonce' => $nonce), $base);
    $concordance = str_replace('{{FV_EX2_CONTEXT_EXPORT}}', esc_url($context_url), $concordance);
    if (strpos($concordance, '{{FV_EX2_') !== false) { status_header(503); exit; }
    // Inject after validating the canonical fragment; keep its original provenance header.
    $chronology_start = '<section class="ex2-section ex2-case" id="chronology"';
    if (substr_count($fragment, $chronology_start) !== 1
        || strpos($fragment, 'id="source-concordance"') !== false
        || strpos($concordance, '<img') !== false || strpos($concordance, '<script') !== false) {
        status_header(503); exit;
    }
    $fragment = str_replace($chronology_start, $concordance . $chronology_start, $fragment);
    $csp_nonce = base64_encode(random_bytes(18));
    nocache_headers();
    header('X-FV-EX2-Apollo-Source-Head: ' . FV_EX2_APOLLO_SOURCE_HEAD);
    header('X-FV-EX2-Apollo-Fragment-SHA256: ' . FV_EX2_APOLLO_SHA256['fragment.html']);
    header('X-FV-EX2-Apollo-CSS-SHA256: ' . FV_EX2_APOLLO_SHA256['apollo.css']);
    header('X-FV-EX2-Apollo-JS-SHA256: ' . FV_EX2_APOLLO_SHA256['apollo.js']);
    header('X-FV-EX2-Apollo-Concordance-SHA256: ' . FV_EX2_APOLLO_SHA256['source-concordance.html']);
    header('X-FV-EX2-Apollo-Context-SHA256: ' . FV_EX2_APOLLO_SHA256['source-context.json']);
    header('Content-Type: text/html; charset=UTF-8');
    header('X-Robots-Tag: noindex, nofollow, noarchive');
    header('X-Content-Type-Options: nosniff');
    header('Referrer-Policy: no-referrer');
    header("Content-Security-Policy: default-src 'none'; script-src 'nonce-{$csp_nonce}'; style-src 'nonce-{$csp_nonce}'; img-src 'none'; font-src 'none'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'self'");
    echo '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
        . '<title>Private Apollo 1 Evidence Review — Final Vestige</title>'
        . '<meta name="robots" content="noindex,nofollow"><style nonce="' . $csp_nonce . '">'
        . $css . $concordance_css . "\n.fv-ex2-apollo__review-h1{position:absolute;width:1px;height:1px;overflow:hidden;clip-path:inset(50%);white-space:nowrap}\n.fv-ex2-apollo__skip{position:absolute;z-index:10000;top:8px;left:8px;padding:12px 18px;background:#0c1010;color:#f2d69b;border:2px solid #f2d69b;transform:translateY(-160%)}\n.fv-ex2-apollo__skip:focus-visible{transform:none;outline:3px solid #f2d69b;outline-offset:3px}"
        . '</style></head><body>'
        . '<a class="fv-ex2-apollo__skip" href="#fv-ex2-apollo-document">Skip to Apollo evidence</a>'
        . '<main id="fv-ex2-apollo-document" class="fv-ex2-apollo" tabindex="-1" aria-label="Apollo 1 evidence investigation">'
        . '<h1 class="fv-ex2-apollo__review-h1">Apollo 1: Research Desk and primary-source casefile</h1>'
        . $fragment . '</main><script nonce="' . $csp_nonce . '">'
        . str_replace('</script', '<\\/script', $js) . '</script></body></html>';
    exit;
}
add_action('wp_ajax_fv_ex2_apollo_sealed_page', 'fv_ex2_apollo_sealed_page');

function fv_ex2_apollo_sealed_download() {
    fv_ex2_apollo_sealed_validate_request();
    $files = array(
        'evidence-export.csv' => 'text/csv; charset=UTF-8',
        'evidence-export.json' => 'application/json; charset=UTF-8',
        'response-export.csv' => 'text/csv; charset=UTF-8',
        'response-export.json' => 'application/json; charset=UTF-8',
        'source-context.json' => 'application/json; charset=UTF-8',
    );
    $file = isset($_GET['file']) && is_string($_GET['file']) ? $_GET['file'] : '';
    if (!array_key_exists($file, $files)) { status_header(404); exit; }
    $raw = fv_ex2_apollo_sealed_asset($file);
    if (!is_string($raw)) { status_header(503); exit; }
    nocache_headers();
    header('X-FV-EX2-Apollo-Source-Head: ' . FV_EX2_APOLLO_SOURCE_HEAD);
    header('X-FV-EX2-Apollo-Asset-SHA256: ' . hash('sha256', $raw));
    header('X-Robots-Tag: noindex, nofollow, noarchive');
    header('X-Content-Type-Options: nosniff');
    header('Cache-Control: no-store, private');
    header('Content-Type: ' . $files[$file]);
    header('Content-Disposition: attachment; filename="apollo-' . $file . '"');
    header('Content-Length: ' . strlen($raw));
    echo $raw;
    exit;
}
add_action('wp_ajax_fv_ex2_apollo_sealed_download', 'fv_ex2_apollo_sealed_download');
