'use strict';
/* Node 22 source-custody regression for private-source WordPress Playground importer. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const home = path.resolve(__dirname,'..');
const blueprint = JSON.parse(fs.readFileSync(path.join(__dirname,'FV_EX2_ASSEMBLER_BLUEPRINT_20261105.json'),'utf8'));
const plugin = blueprint.steps.find(s=>s.step==='writeFile')?.data;
assert.equal(blueprint.steps.length,4);
assert.equal(blueprint.steps[0].themeData.ref,'75faa8a1e0367a37c2638250a3c9ed0a0f8c0b7f');
assert.ok(blueprint.steps[0].themeData.url.endsWith('Automattic/themes'));
assert.ok(plugin.includes('if (!is_page(\'fv-ex2-review\'))'));
assert.ok(blueprint.steps.find(s=>s.step==='runPHP').code.includes('wp_insert_post('));
const origin = fs.readFileSync(path.join(home,'index.html'),'utf8');
const marker = '<div class="fv-hf" data-fv-home-flagship>';
let section = origin.slice(origin.indexOf(marker),origin.lastIndexOf('</body>')).trim();
assert.ok(section.startsWith(marker));
assert.equal(section.split('<main>').length - 1,1);
assert.equal(section.split('</main>').length - 1,1);
section = section.replace('<main>','<div class="fv-hf__wp-content">').replace('</main>','</div>');
assert.ok(plugin.includes(section),'page content must match the exact canonical candidate, except the nested-main transformation');
const css = ["flagship.css","chronicle.css","chronicle-lens.css","inquiry.css","observer-lab.css","reading-trail.css"];
const js = ["flagship.js","observer-lab.js","chronicle-lens.js","reading-trail.js"];
for(const name of css) assert.ok(plugin.includes(fs.readFileSync(path.join(home,name),'utf8')),'CSS mismatch: '+name);
for(const name of js) assert.ok(plugin.includes(fs.readFileSync(path.join(home,name),'utf8')),'JS mismatch: '+name);
assert.equal(section.split('<img ').length - 1,2);
assert.ok(section.includes('https://finalvestige.com/focus/'));
assert.ok(!section.includes('<script src='));
assert.ok(!section.includes('<main>'));
// Native PHP parser + accidental-copy behavior is mandatory; never skip silently.
require('./verify_playground_php_preflight.cjs');
console.log('PASS: exact-source importer plus native PHP preflight');
