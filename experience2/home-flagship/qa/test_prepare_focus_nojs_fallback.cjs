'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {prepare,CURRENT_MODIFIED,PDF}=require('./prepare_focus_nojs_fallback.cjs');
const block=fs.readFileSync(path.join(__dirname,'focus_nojs_fallback_block.html'),'utf8');
const original='<!-- wp:group {"className":"fv-focus"} --><div class="wp-block-group alignfull fv-focus">'+ 'x'.repeat(6000) +'<!-- wp:jetpack/subscriptions {"showSubscribersTotal":false} /-->'+'<!-- wp:html --><div id="fvf-gift" class="gift" hidden role="status"><a href="'+PDF+'">Download</a></div><!-- /wp:html --></div><!-- /wp:group -->';
const seed=()=>({id:1579,status:'publish',modified:CURRENT_MODIFIED,content:original});
const negative=(name,fn)=>test(name,()=>assert.throws(fn));
test('surgical insertion preserves Jetpack and hidden gift',()=>{
 const result=prepare(seed(),block);
 assert.equal(result.split('<!-- wp:jetpack/subscriptions').length-1,1);
 assert.equal(result.split('id="fvf-gift"').length-1,1);
 assert.equal(result.split('<noscript>').length-1,1);
 assert.ok(result.indexOf('<noscript>')>result.indexOf('wp:jetpack/subscriptions'));
 assert.ok(result.indexOf('<noscript>')<result.indexOf('id="fvf-gift"'));
 assert.ok(result.includes('Downloading here does not subscribe'));
 assert.equal(result.split(PDF).length-1,2);
});
negative('reject changed WordPress revision',()=>prepare({...seed(),modified:'2026-11-06T01:01:01'},block));
negative('reject wrong WordPress page',()=>prepare({...seed(),id:6},block));
negative('reject missing Jetpack subscription block',()=>prepare({...seed(),content:original.replace('wp:jetpack/subscriptions','wp:paragraph')},block));
negative('reject duplicate Jetpack subscription block',()=>prepare({...seed(),content:original+original},block));
negative('reject unverified PDF asset',()=>prepare({...seed(),content:original.replace(PDF,'https://example.org/unknown.pdf')},block));
negative('reject already patched page',()=>prepare({...seed(),content:original+block},block));
negative('reject missing hidden-gift sentinel',()=>prepare({...seed(),content:original.replace('hidden role','role')},block));
negative('reject tracking added to fallback',()=>prepare(seed(),block.replace('</noscript>','<script>track()</script></noscript>')));
negative('reject missing genuinely no-JS markup',()=>prepare(seed(),block.replace('<noscript>','<div>').replace('</noscript>','</div>')));
negative('reject malformed content',()=>prepare({...seed(),content:'no markup'},block));
