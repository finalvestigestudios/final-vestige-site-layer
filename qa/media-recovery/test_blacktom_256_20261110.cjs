'use strict';
const {test}=require('node:test');const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {validate}=require('./validate_blacktom_256_20261110.cjs');
const here=__dirname;const read=n=>JSON.parse(fs.readFileSync(path.join(here,n),'utf8'));
const batch=read('blacktom_256_seven_loc_newspaper_rights_20261110.json');
const full=read('coverage_222_exact_pr1703_20261110.json');
