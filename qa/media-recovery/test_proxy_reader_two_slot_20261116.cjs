'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {assess}=require('./assess_proxy_reader_two_slot_20261116.cjs');
const fixture=JSON.parse(fs.readFileSync(path.join(__dirname,'proxy_reader_two_slot_20261116.json'),'utf8'));
const clone=()=>JSON.parse(JSON.stringify(fixture));
test('valid source-reader evidence remains HOLD',()=>{const r=assess(clone());assert.equal(r.ok,true);assert.equal(r.decision,'HOLD_BROWSER_AND_ITEM_RIGHTS');});
test("reject guest 404",()=>{const x=clone();x.rows[0].guest_http=404;assert.equal(assess(x).ok,false);});
test("reject reader 200",()=>{const x=clone();x.rows[1].reader_http=200;assert.equal(assess(x).ok,false);});
test("reject origin 403",()=>{const x=clone();x.rows[1].origin_http=403;assert.equal(assess(x).ok,false);});
test("reject decoded true",()=>{const x=clone();x.rows[0].guest_decode=true;assert.equal(assess(x).ok,false);});
test("reject currentSrc",()=>{const x=clone();x.rows[0].guest_current_src=x.rows[0].url;assert.equal(assess(x).ok,false);});
test("reject transfer",()=>{const x=clone();x.rows[1].guest_transfer_bytes=100;assert.equal(assess(x).ok,false);});
test("reject native dimensions",()=>{const x=clone();x.rows[0].native_dimensions=[960,800];assert.equal(assess(x).ok,false);});
test("reject binary hash",()=>{const x=clone();x.rows[1].binary_sha256='a'.repeat(64);assert.equal(assess(x).ok,false);});
test("reject cache",()=>{const x=clone();x.rows[0].wp_cached=true;assert.equal(assess(x).ok,false);});
test("reject rights",()=>{const x=clone();x.rows[0].rights='CLEARED';assert.equal(assess(x).ok,false);});
test("reject source rights",()=>{const x=clone();x.rows[1].reference_rights='CLEARED';assert.equal(assess(x).ok,false);});
test("reject upscale",()=>{const x=clone();x.rows[1].max_width=1920;assert.equal(assess(x).ok,false);});
test("reject url drift",()=>{const x=clone();x.rows[0].url='https://example.com/abc.jpg';assert.equal(assess(x).ok,false);});
test("reject slot drift",()=>{const x=clone();x.rows[0].slot='285:5';assert.equal(assess(x).ok,false);});
test("reject identity drift",()=>{const x=clone();x.rows[1].relation='EXACT';assert.equal(assess(x).ok,false);});
test("reject wrong catalog",()=>{const x=clone();x.rows[1].official_reference='https://example.com';assert.equal(assess(x).ok,false);});
test("reject 42 claim",()=>{const x=clone();x.claimed_42_browser_broken=true;assert.equal(assess(x).ok,false);});
test("reject 76 claim",()=>{const x=clone();x.measured_76_percent_savings=true;assert.equal(assess(x).ok,false);});
test("reject faked bytes",()=>{const x=clone();x.large_stored.visitor_transfer_bytes=64385752;assert.equal(assess(x).ok,false);});
test("reject auto replacement",()=>{const x=clone();x.automatic_replace=true;assert.equal(assess(x).ok,false);});
test("reject production",()=>{const x=clone();x.production_write=true;assert.equal(assess(x).ok,false);});
test("reject missing row",()=>{const x=clone();x.rows.pop();assert.equal(assess(x).ok,false);});
test("reject census drift",()=>{const x=clone();x.historical.images=361;assert.equal(assess(x).ok,false);});
test("reject different method",()=>{const x=clone();x.observation_method='COLD_BROWSER';assert.equal(assess(x).ok,false);});
