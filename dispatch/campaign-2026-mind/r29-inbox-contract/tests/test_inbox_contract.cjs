'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {audit,reviewHtml,HOLD}=require('../inbox_contract.cjs');
const root=path.resolve(__dirname,'../..'),m=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
const sources=m.issues.map(x=>fs.readFileSync(path.join(root,'issues',String(x.number).padStart(2,'0')+'-'+x.slug+'.md'),'utf8'));
const blocks=m.issues.map(x=>fs.readFileSync(path.join(root,'wordpress-post-bridge-r23','proofs','issue-'+String(x.number).padStart(2,'0')+'.blocks.html'),'utf8').split('\n')[0]);
const f={auto:false,mode:'excerpt',native:false,postal:false,unsub:false};
let tests=0;function check(v,label){assert.ok(v,label);tests++}
const result=audit(m,sources,blocks,f);
check(result.errors.length===0,'exact current campaign source');
check(result.issues.length===6,'six issues');
check(!result.release_ready && result.not_actual_jetpack_email,'unsent');
check(result.issues.filter(x=>x.kind==='commercial-review-pending').length===2,'4:2');
for(const x of result.issues){check(x.first_native_candidate_block_is_hold,'hold first');check(!x.cta_in_350&&!x.cta_in_55,'CTA outside short excerpts');check(!x.received_email_proven&&!x.legal_footer_proven,'no false native/legal proof')}
check(result.issues.filter(x=>x.commercial_disclosure_in_350===false).length===2,'commercial disclosure excerpt risk');
check(reviewHtml(result).includes('NOT an actual Jetpack email'),'clear static disclaimer');
const mut=(change)=>{const a=structuredClone(m),s=sources.slice(),b=blocks.slice(),o={...f};change(a,s,b,o);return audit(a,s,b,o).errors.length>0};
check(mut(a=>a.status='SENT'),'unsent gate');
check(mut(a=>a.mix.editorial=6),'mix gate');
check(mut(a=>a.issues[0].publish_state='publish'),'publish gate');
check(mut(a=>a.issues[2].merchant_affiliate_url='https://invalid.example'),'affiliate gate');
check(mut(a=>a.issues[2].kind='editorial'),'role gate');
check(mut((a,s,b)=>b[0]=b[0].replace(HOLD,'PUBLISH NOW')),'Gutenberg hold gate');
check(mut((a,s)=>s[0]=s[0].replace('[[VALID_POSTAL_ADDRESS_REQUIRED]]','real-looking-address')),'postal gate');
check(mut((a,s)=>s[0]=s[0].replace('[[JETPACK_UNSUBSCRIBE_LINK_MUST_BE_VERIFIED]]','looks-like-unsub')),'unsubscribe gate');
check(mut((a,s)=>s[2]=s[2].replace('**Commercial disclosure:**','**Advertisement:**')),'commercial disclosure gate');
check(mut((a,s)=>s[1]=s[1].replace('**Subject:** Before hypnosis had a name','**Subject:** Guess what happened')),'subject gate');
check(mut((a,s)=>s[3]=s[3].replace(a.issues[3].editorial_cta,'https://example.com/now')),'CTA gate');
check(mut((a,s)=>s[3]=s[3].replace('The surviving recording','clickbank tracking The surviving recording')),'tracking gate');
check(mut((a,s,b,o)=>o.auto=true),'auto-email gate');
check(mut((a,s,b,o)=>o.mode='full'),'unexpected global format gate');
check(mut((a,s,b,o)=>o.native=true),'false received email gate');
check(mut((a,s,b,o)=>o.postal=true),'false address proof gate');
check(mut((a,s,b,o)=>o.unsub=true),'false unsubscribe gate');
console.log('PASS '+tests+' assertions, including 17 fail-closed mutations; no posts, sends, network or PII');