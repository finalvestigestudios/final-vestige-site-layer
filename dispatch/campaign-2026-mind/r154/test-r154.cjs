// Run: node test-r154.cjs  (Node built-ins only; offline, never sends).
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=__dirname;
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const data=JSON.parse(read('04-review.json'));
const md=read('04-OPTIONAL-UNSENT.md'),html=read('04-email-preview.html'),txt=read('04-email-preview.txt'),review=read('R154-COPY-CONVERSION-AUDIT.md');
const assertions=[];
const check=(name,fn)=>{fn();assertions.push(name)};
check('issue04',()=>assert.equal(data.issue,4));
check('still editorial',()=>assert.equal(data.kind,'editorial'));
check('not sendable',()=>assert.equal(data.send_authorized,false));
check('no merchant',()=>assert.equal(data.commercial_offer,null));
check('one primary CTA',()=>assert.equal((md.match(/\*\*Read the investigation:\*\*/g)||[]).length,1));
check('CTA first-party',()=>assert.match(data.cta.url,/^https:\/\/finalvestige\.com\/2026\/08\/20\//));
check('source citation original NASA',()=>assert.ok(data.sources.some(s=>s.url.includes('/Apollo204/find.html'))));
check('second authoritative source',()=>assert.ok(data.sources.some(s=>s.url.includes('sma.nasa.gov'))));
check('subject exact',()=>{assert.ok(md.includes(data.subject));assert.ok(html.includes(data.subject));assert.ok(txt.includes(data.subject))});
check('preheader exact',()=>{assert.ok(md.includes(data.preheader));assert.ok(html.includes(data.preheader));assert.ok(txt.includes(data.preheader))});
check('mail marked draft',()=>{assert.match(html,/UNSENT REVIEW MOCKUP/);assert.match(txt,/UNSENT DRAFT/)});
check('unresolved postal',()=>{for(const s of [md,html,txt])assert.ok(s.includes('[[VALID_POSTAL_ADDRESS_REQUIRED]]'))});
check('unresolved unsubscribe',()=>{for(const s of [md,html,txt])assert.ok(s.includes('[[JETPACK_UNSUBSCRIBE_LINK_MUST_BE_VERIFIED]]'))});
check('no seller links',()=>{for(const s of [md,html,txt])assert.ok(!/https?:\/\/(zen12|hypnosislive|inspire3)\./i.test(s))});
check('no JS / pixels',()=>{assert.ok(!/<script|<img|utm_|<form/i.test(html))});
check('email safe tables',()=>assert.match(html,/table role="presentation"/));
check('lang and viewport',()=>{assert.match(html,/lang="en"/);assert.match(html,/name="viewport"/)});
check('one actual promo button',()=>assert.equal((html.match(/display:inline-block;background:/g)||[]).length,1));
check('no false proof',()=>assert.ok(!/proven that the wire|identified the exact spark|guaranteed to cure/i.test(md)));
check('all content paragraphs in both renderings',()=>{for(const s of data.sections){assert.ok(md.includes(s.text));assert.ok(html.includes(s.text.replace(/&/g,'&amp;')));assert.ok(txt.includes(s.type==='h2'?s.text.toUpperCase():s.text))}});
check('all primary source links appear',()=>{for(const s of data.sources)for(const body of [md,html,txt])assert.ok(body.includes(s.url))});
check('honest critique canonical six',()=>{for(const x of ['| 01 |','| 02 |','| 03 |','| 04 |','| 05 |','| 06 |'])assert.ok(review.includes(x))});
check('commercial issues held',()=>{assert.match(review,/HOLD_MERCHANT = 03,05/);assert.match(review,/HOLD_UNSENT = 01\.\.06/)});
check('audited false count',()=>assert.match(review,/total=3, confirmed=3, unconfirmed=2/));
check('revenue not computable',()=>assert.match(review,/NOT COMPUTABLE/));
console.log('PASS '+assertions.length+'/'+assertions.length+' R154 native Node content/source/copy checks');
