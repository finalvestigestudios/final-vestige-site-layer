import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=dirname(fileURLToPath(import.meta.url));
const src=n=>readFileSync(join(dir,n),'utf8');
const m=src('ISSUE02_OPTIONAL.md'), t=src('ISSUE02_OPTIONAL.txt'), h=src('ISSUE02_OPTIONAL.html');
const claims=JSON.parse(src('PRIMARY_SOURCE_AND_OFFER_ALIGNMENT.json'));
const gate=JSON.parse(src('NO_SEND_RELEASE_GATE.json'));
const decision=src('TRANSPORT_AND_CONVERSION_DECISION.md');
const subject='The strange sleep recorded in 1784';
const pre='A patient, a privately circulated memoir, and what could be repeated.';
const cta='https://finalvestige.com/2026/11/02/mesmerism/';
const copies=[m,t,h];
test('headline matches all copies',()=>assert.ok(copies.every(s=>s.includes(subject))));
test('preheader matches all copies',()=>assert.ok(copies.every(s=>s.includes(pre))));
test('subject short',()=>assert.ok([...subject].length<=55));
test('preheader short',()=>assert.ok([...pre].length<=110));
test('one actionable primary CTA each',()=>assert.ok(copies.every(s=>s.split(cta).length-1===1)));
test('draft has no merchant checkout or earning URL',()=>assert.ok(copies.every(s=>!/https?:\/\/(?:www\.)?(?:zen12|hypnosislive|affiliates\.inspire3)/i.test(s))));
test('no script pixel iframe video or form',()=>assert.ok(!/<(script|img|form|iframe|video)\b/i.test(h)));
test('HTML document language',()=>assert.ok(h.includes('lang="en"')));
test('HTML viewport',()=>assert.ok(h.includes('name="viewport"')));
test('semantic headings',()=>assert.ok(h.includes('<h1')&&h.includes('<h2')));
test('email table presentation roles',()=>assert.ok(h.includes('role="presentation"')));
test('offline warning visible',()=>assert.ok(h.includes('NOT A NATIVE JETPACK RENDER')));
test('no fake unsubscribe',()=>assert.ok(!/href=["\']#unsubscribe/i.test(h)));
test('hold address in all copies',()=>assert.ok(copies.every(s=>s.includes('[[VALID_POSTAL_ADDRESS_REQUIRED]]'))));
test('hold unsub in all copies',()=>assert.ok(copies.every(s=>s.includes('[[JETPACK_UNSUBSCRIBE_LINK_MUST_BE_VERIFIED]]'))));
test('all cited historical sources in every copy',()=>{for(const c of claims.historical_claims)for(const s of copies)assert.ok(s.includes(c.source))});
test('no proof that 50 people repeated results',()=>assert.equal(claims.historical_claims[2].independent_fifty_successes,false));
test('no direct historical pdf claimed',()=>assert.equal(claims.primary_pdf_directly_reviewed,false));
test('full book not falsely claimed',()=>assert.equal(claims.full_2025_book_reviewed,false));
test('original campaign preserved',()=>assert.equal(gate.orig_six_modified,false));
test('4 editorial, 2 commercial',()=>{assert.equal(gate.campaign_ratio.editorial,4);assert.equal(gate.campaign_ratio.commercial_reserved,2)});
test('all six holds',()=>assert.ok(gate.issues.length===6&&gate.issues.every(i=>i.can_send===false)));
test('two commercial holds',()=>assert.deepEqual(gate.issues.filter(i=>i.release.includes('HOLD_MERCHANT')).map(i=>i.number),[3,5]));
test('unknown unique inbox count stays null',()=>assert.equal(gate.source_of_truth.unique_email_receiving_subscribers,null));
test('unconfirmed are not added to total',()=>{assert.equal(gate.source_of_truth.jetpack_total,3);assert.equal(gate.source_of_truth.jetpack_unconfirmed,2)});
test('no actual received welcome',()=>assert.equal(gate.source_of_truth.actual_welcome_received,false));
test('no native email render',()=>assert.equal(gate.source_of_truth.native_preview_email_captured,false));
test('legal address and optout unverified',()=>{assert.equal(gate.source_of_truth.rendered_publisher_postal_address_verified,false);assert.equal(gate.source_of_truth.functional_unsubscribe_verified,false)});
test('no affiliate email permissions',()=>{assert.equal(gate.merchant.zen12_email_rights,false);assert.equal(gate.merchant.total_focus_email_rights,false)});
test('no merchant links issued',()=>{assert.equal(gate.merchant.zen12_earning_url,false);assert.equal(gate.merchant.total_focus_earning_url,false)});
test('no final founder send approval',()=>assert.equal(gate.founder_final_campaign_approval,false));
test('no fabricated revenue',()=>assert.equal(gate.realized_net_revenue_per_1000_qualified_sessions,null));
test('decision distinguishes actual sales',()=>assert.ok(decision.includes('independently settled paid affiliate conversion')));
test('FTC and provider docs linked',()=>assert.ok(decision.includes('ftc.gov')&&decision.includes('wordpress.com/support')));
