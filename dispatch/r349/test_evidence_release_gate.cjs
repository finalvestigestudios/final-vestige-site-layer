"use strict";
const assert=require("node:assert/strict");
const {inspectOffer,inspectNewsletter,inspectCohort}=require("./evidence_release_gate.cjs");
const evidence=require("./evidence_snapshot.json");
let count=0;
function test(name,fn){try{fn();count++;process.stdout.write("PASS "+name+"\n");}catch(e){process.stderr.write("FAIL "+name+" "+e.message+"\n");process.exitCode=1;}}
const offers=evidence.merchant.map(inspectOffer);
const letter=inspectNewsletter(evidence.wordpress.newsletter);
test("two merchant rows",()=>assert.equal(offers.length,2));
test("all merchants remain hold",()=>assert.ok(offers.every(o=>o.status==="HOLD_MERCHANT")));
test("no merchant link allowed",()=>assert.ok(offers.every(o=>o.do_not_activate_link)));
test("public prices not authorized",()=>assert.ok(offers.every(o=>o.do_not_quote_price)));
test("Total Focus public promotional price disagreement flagged",()=>assert.equal(offers[1].public_price_conflict,true));
test("Zen12 different SKUs are not same-product price drift",()=>assert.equal(offers[0].public_price_conflict,false));
test("Zen12 ambiguous offer paths flagged separately",()=>assert.equal(offers[0].incomparable_offer_variants,true));
test("cannot treat coupon and other package as checkout",()=>assert.equal(evidence.merchant[0].proofs.issued_earning_url,undefined));
test("all release proofs missing",()=>assert.equal(offers[0].missing_proofs.length,7));
test("newsletter still hold",()=>assert.equal(letter.status,"HOLD_UNSENT"));
test("subscriber count non-additive",()=>assert.equal(letter.counts_are_nonadditive,true));
test("follower counts not added to recipients",()=>assert.equal(letter.actual_eligible_inbox_count,null));
test("auto-send off",()=>assert.equal(evidence.wordpress.newsletter.auto_post_enabled,false));
test("welcome receipt unresolved",()=>assert.ok(letter.reasons.includes("WELCOME_RECEIPT_NOT_VERIFIED")));
test("native inbox unresolved",()=>assert.ok(letter.reasons.includes("NATIVE_RECEIVED_RENDER_NOT_VERIFIED")));
test("postal address unresolved",()=>assert.ok(letter.reasons.includes("PUBLISHER_ADDRESS_NOT_VERIFIED")));
test("unsubscribe unresolved",()=>assert.ok(letter.reasons.includes("UNSUBSCRIBE_NOT_VERIFIED")));
test("founder approval unresolved",()=>assert.ok(letter.reasons.includes("FOUNDER_FINAL_APPROVAL_MISSING")));
test("zero without merchant evidence is unknown",()=>assert.equal(inspectCohort({qualified_human_sessions:200,provider_verified:true,orders:[],orders_complete_verified:false}).status,"NOT_COMPUTABLE"));
const done={qualified_human_sessions:200,provider_verified:true,orders:[],orders_complete_verified:true};
test("zero only from complete merchant reporting",()=>assert.equal(inspectCohort(done).net_per_1000,0));
const order={id:"synthetic-hash",type:"affiliate",currency:"USD",settled:true,refunds_final:true,fees_final:true,gross:12,refunds:3,fees:1};
test("synthetic settlement formula",()=>assert.equal(inspectCohort({...done,orders:[order]}).net_per_1000,40));
test("duplicate order rejected",()=>assert.equal(inspectCohort({...done,orders:[order,order]}).status,"NOT_COMPUTABLE"));
test("click is not sale",()=>assert.equal(inspectCohort({...done,orders:[{...order,type:"click"}]}).status,"NOT_COMPUTABLE"));
test("pending order is not sale",()=>assert.equal(inspectCohort({...done,orders:[{...order,settled:false}]}).status,"NOT_COMPUTABLE"));
test("uncleared fees rejected",()=>assert.equal(inspectCohort({...done,orders:[{...order,fees_final:false}]}).status,"NOT_COMPUTABLE"));
test("unknown denominators rejected",()=>assert.equal(inspectCohort({...done,provider_verified:false}).status,"NOT_COMPUTABLE"));
test("all original editions still unsent",()=>assert.equal(evidence.sending_authorized,false));
test("original 4:2 invariant",()=>assert.deepEqual(evidence.github.founder_original_allocation,{editorial:4,commercial_review_pending:2}));
test("zero alternates adopted",()=>assert.equal(evidence.github.alternates_adopted,0));
test("no PII in snapshot",()=>assert.ok(!/\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/i.test(JSON.stringify(evidence))));
process.stdout.write("TOTAL "+count+" tests, "+(process.exitCode?"FAILED":"PASSED")+"\n");
