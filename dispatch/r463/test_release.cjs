'use strict';
// Source-only read of this R463 directory; NEVER a mail sender or analytics script.
// Run after checking out the exact PR head: node dispatch/r463/test_release.cjs
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=__dirname, read=n=>fs.readFileSync(path.join(base,n),'utf8');
const md=read('ISSUE03_EVIDENCE_FIRST_OPTION.md');
const html=read('ISSUE03_OFFLINE_REVIEW.html');
const txt=read('ISSUE03_OFFLINE_REVIEW.txt');
const j=JSON.parse(read('RELEASE_AND_SOURCE_LEDGER.json'));
const docket=read('R463_OWNER_RELEASE_DOCKET.md');
const subject='What twelve minutes can—and cannot—prove';
const preheader='A free seven-day attention test, and the claim an audio seller still has to support.';
const postal='[[VALID_POSTAL_ADDRESS_REQUIRED]]',optout='[[JETPACK_UNSUBSCRIBE_LINK_MUST_BE_VERIFIED]]';
const witness='[[NATIVE_JETPACK_PREVIEW_NOT_WITNESSED]]';
const permission='[[PARTNER_EMAIL_APPROVAL_NOT_VERIFIED]]';
let n=0; const test=(name,fn)=>{try{fn();n++;process.stdout.write('PASS '+name+'\n')}catch(e){process.stderr.write('FAIL '+name+': '+e.message+'\n');process.exitCode=1}};
test('title consistent',()=>assert([md,html,txt].every(x=>x.includes(subject))));
test('preheader consistent',()=>assert([md,html,txt].every(x=>x.includes(preheader))));
test('single first-party action',()=>assert.equal(html.split('href="https://finalvestige.com/focus/"').length-1,1));
test('not a verified affiliate link',()=>assert(!/href="[^"]+(affiliate|affid|refid|coupon)/i.test(html)));
test('sender unsent state',()=>assert(html.includes('HOLD UNSENT — OFFLINE REVIEW ONLY')));
test('no JS or tracking pixels',()=>assert(!/<script|<iframe|<img/gi.test(html)));
test('no remote CSS',()=>assert(!/<link[^>]+stylesheet/i.test(html)));
test('600px table email review',()=>assert(html.includes('max-width:600px')&&html.includes('role="presentation"')));
test('language declaration',()=>assert(html.includes('<html lang="en">')));
test('one H1',()=>assert.equal((html.match(/<h1\b/g)||[]).length,1));
test('CTA context',()=>assert(html.includes('Open the free Seven Day Focus Fieldbook')));
test('meditation source',()=>assert(html.includes('www.nccih.nih.gov/health/meditation-and-mindfulness-effectiveness-and-safety')));
test('auditory beats primary abstract',()=>assert(html.includes('pubmed.ncbi.nlm.nih.gov/30073406/')));
test('exact official seller description',()=>assert(html.includes('https://zen12.com/about')));
test('exact official seller product page',()=>assert(html.includes('https://zen12.com/?no-popup=1')));
test('commercial adjacency',()=>assert(html.indexOf('Commercial disclosure:')>html.indexOf('Commercial placement reserved') && html.indexOf('Commercial disclosure:')<html.indexOf('Full source links')));
for(const [name,token] of [['postal',postal],['unsubscribe',optout],['native preview',witness],['email permission',permission]])test('blocked '+name,()=>assert([md,html,txt].every(x=>x.includes(token))));
test('four editorial, two commercial',()=>assert.deepEqual(j.slots,{editorial:[1,2,4,6],commercial_reserved:[3,5]}));
test('partner email rights unverified',()=>assert.equal(j.offer.email_channel_approval_verified,false));
test('earning URL unverified',()=>assert.equal(j.offer.earning_url_verified,false));
test('sales unverified',()=>assert.equal(j.offer.affiliate_paid_order_verified,false));
test('welcome receipt unverified',()=>assert.equal(j.newsletter.welcome_received,false));
test('provider numbers unreconciled',()=>assert.equal(j.counts.provider_reconciled,false));
test('no independently acquired lead count',()=>assert.equal(j.counts.independent_human_acquisitions,null));
test('realized revenue metric not computable',()=>assert.equal(j.kpis.net_revenue_per_thousand_qualified_human_sessions,null));
test('newsletter default off',()=>assert.equal(j.newsletter.auto_new_post_email,false));
test('no permission to send',()=>assert.equal(j.publisher_approved_to_send,false));
test('no send',()=>assert.equal(j.cta.sent,false));
test('FTC source recorded',()=>assert(docket.includes('ftc.gov/business-guidance/resources/can-spam-act')));
test('no unsupported health promise',()=>assert(!/cures anxiety|clinically proven to reprogram|guaranteed to work/i.test([html,txt].join(' '))));
const safety=s=>s.includes('HOLD UNSENT')&&s.includes('Commercial disclosure:')&&s.includes(postal)&&!/<script/i.test(s);
for(const [name,altered] of [['removed disclosure',html.replace('Commercial disclosure:','Disclosure removed')],['fake postal',html.replace(postal,'fictional address')],['script injected',html+'<script src="https://test.invalid"></script>'],['release state altered',html.replace('HOLD UNSENT','SEND NOW')]])test('detect mutation: '+name,()=>assert.equal(safety(altered),false));
process.stdout.write('R463 source-only checks executed: '+n+' assertions, '+(process.exitCode?'FAIL':'PASS')+'\n');
if(process.exitCode)process.exit(process.exitCode);
