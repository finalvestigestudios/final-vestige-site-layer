"use strict";
const fs=require("node:fs"), path=require("node:path"), assert=require("node:assert/strict");
const dir=__dirname;
const text=n=>fs.readFileSync(path.join(dir,n),"utf8");
const a=text("issue04-apollo-clock-review.md"), b=text("issue04-apollo-clock-review.txt"), c=text("issue04-apollo-clock-review.html"), m=JSON.parse(text("manifest.json")), x=text("source-and-release-matrix.md"), y=text("consent-to-revenue-spec.md");
const checks=[];
const check=(name,fn)=>checks.push([name,fn]);
check("hold state",()=>assert.equal(m.status,"REVIEW_ONLY_NOT_ADOPTED_HOLD_UNSENT"));
check("historical editorial only",()=>assert.equal(m.issue.kind,"editorial"));
check("merchant inactive",()=>assert.equal(m.issue.merchant_url,null));
check("no commercial placement",()=>assert.equal(m.issue.commercial_placement,false));
check("approved official Board source",()=>assert.ok(m.sources[0].includes("nasa.gov")));
check("source references three NASA links in review",()=>m.sources.forEach(u=>assert.ok(a.includes(u))));
check("source references in plaintext",()=>m.sources.forEach(u=>assert.ok(b.includes(u))));
check("source references in HTML",()=>m.sources.forEach(u=>assert.ok(c.includes(u.replaceAll("&","&amp;")))));
check("single editorial CTA in markdown",()=>assert.equal((a.match(/Read the Apollo 1 Evidence Atlas:/g)||[]).length,1));
check("single editorial CTA in text",()=>assert.equal((b.match(/READ THE APOLLO 1 EVIDENCE ATLAS:/g)||[]).length,1));
check("single editorial CTA in HTML",()=>assert.equal((c.match(/>Read the Apollo 1 Evidence Atlas<\/a>/g)||[]).length,1));
check("verified CTA string",()=>[a,b,c].forEach(s=>assert.ok(s.includes(m.issue.primary_cta))));
check("subjects all formats",()=>[a,b,c].forEach(s=>assert.ok(s.includes(m.issue.subject))));
check("preheaders all formats",()=>[a,b,c].forEach(s=>assert.ok(s.includes(m.issue.preheader))));
check("no unqualified 14 second subject",()=>[a,b,c].forEach(s=>assert.ok(!s.includes("Fourteen seconds. A much longer explanation."))));
check("specific fire-report timestamp",()=>[a,b,c].forEach(s=>assert.ok(s.includes("23:31:04.7"))));
check("specific rupture timestamp",()=>[a,b,c].forEach(s=>assert.ok(s.includes("23:31:19"))));
check("declared uncertainty",()=>[a,b,c].forEach(s=>assert.ok(/not.*(?:start|stopwatch|ignition|moment)|not conclusively/i.test(s))));
check("unverified footer in text and html",()=>[b,c].forEach(s=>assert.ok(s.includes("ACTUAL_JETPACK_UNSUBSCRIBE_NOT_VERIFIED"))));
check("valid postal address not falsely claimed",()=>[b,c].forEach(s=>assert.ok(s.includes("VALID_FINAL_VESTIGE_POSTAL_ADDRESS_NOT_VERIFIED"))));
check("provider render not falsely claimed",()=>assert.ok(c.includes("NOT A JETPACK PREVIEW")));
check("accessible language",()=>assert.ok(c.includes('<html lang="en">')));
check("presentation tables",()=>assert.ok(c.includes('role="presentation"')));
check("heading included",()=>assert.ok(c.includes("<h1")));
check("no scripts or tracking pixels",()=>assert.ok(!/<script|<iframe|<img/i.test(c)));
check("avoid seller URLs in actual issue variants",()=>[a,b,c].forEach(s=>assert.ok(!/zen12\.com|hypnosislive\.com|inspire3\.com/i.test(s))));
check("no invented affiliate prices",()=>[a,b,c].forEach(s=>assert.ok(!/\$\d+(?:\.\d{2})?/i.test(s))));
check("evidence boundary",()=>assert.ok(x.includes("roughly 14.3 sec")));
check("no PII",()=>assert.ok(y.includes("never expose addresses")));
check("gated cohort math",()=>assert.ok(y.includes("NOT COMPUTABLE")));
check("no enabled release",()=>Object.values(m.release).forEach(v=>assert.equal(v,false)));
let failed=0;
for(const [name,fn] of checks){try{fn();console.log("PASS "+name)}catch(err){failed++;console.error("FAIL "+name+": "+err.message)}}
console.log((checks.length-failed)+"/"+checks.length+" tests passed");if(failed)process.exitCode=1;
